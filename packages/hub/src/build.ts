// BuildRunner (spec 03 §3.6-3.8, 08 §8.6): profile + board -> generated board fragment ->
// idf.py in the sanitized IDF environment -> artifact ingest.

import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { checkSourceDir, idfEnv, idfStatus, readIdfLock, run } from '@fractonica/host';
import { FrError } from '@fractonica/protocol';
import { parse as parseYaml } from 'yaml';

import { ingestBuild, lastFwId } from './artifacts.ts';
import type { Db } from './db.ts';
import type { JobCtx } from './jobs.ts';
import { stripAnsi } from './logstore.ts';

interface ProfileFile {
  profile: string;
  board: string;
  app: string;
}

interface BoardFile {
  id: string;
  idf_target: string;
  flash: { size: string; part_profile: string };
  console: string;
  psram: null | { mode: string };
}

export interface ResolvedProfile {
  profile: string;
  app: string;
  board: string;
  target: string;
  partProfile: string;
  fragment: string;
}

function readYaml<T>(file: string, what: string): T {
  if (!existsSync(file)) {
    throw new FrError('NOT_FOUND', `${what} not found: ${file}`);
  }
  return parseYaml(readFileSync(file, 'utf8')) as T;
}

/** C1 subset of `fr gen firmware`: resolves a profile and renders its sdkconfig.board fragment. */
export function resolveProfile(sourceDir: string, name: string): ResolvedProfile {
  const profile = readYaml<ProfileFile>(join(sourceDir, 'firmware', 'profiles', `${name}.profile.yaml`), `profile ${name}`);
  const board = readYaml<BoardFile>(join(sourceDir, 'hardware', 'boards', `${profile.board}.board.yaml`), `board ${profile.board}`);
  const csv = join(sourceDir, 'firmware', 'partitions', `${board.flash.part_profile}.csv`);
  if (!existsSync(csv)) {
    throw new FrError('NOT_FOUND', `partition table ${csv} not found`);
  }
  const lines = [
    '# GENERATED by the Fractonica hub from the profile and board manifest. Do not edit.',
    `CONFIG_IDF_TARGET="${board.idf_target}"`,
    `CONFIG_ESPTOOLPY_FLASHSIZE_${board.flash.size.toUpperCase()}=y`,
    `CONFIG_PARTITION_TABLE_CUSTOM_FILENAME="${csv}"`,
    ...(board.console === 'usb_serial_jtag' ? ['CONFIG_ESP_CONSOLE_USB_SERIAL_JTAG=y'] : []),
    `CONFIG_FR_BOARD="${board.id}"`,
    `CONFIG_FR_PROFILE="${profile.profile}"`,
    `CONFIG_FR_PART_PROFILE="${board.flash.part_profile}"`,
    '',
  ];
  return { profile: profile.profile, app: profile.app, board: board.id, target: board.idf_target, partProfile: board.flash.part_profile, fragment: lines.join('\n') };
}

const DIAG_RE = /^(.+?):(\d+):(\d+): (fatal error|error|warning): (.*)$/;

export interface Diagnostic {
  file: string;
  line: number;
  col: number;
  severity: string;
  message: string;
}

export function parseDiagnostic(line: string): Diagnostic | null {
  const m = DIAG_RE.exec(line);
  return m ? { file: m[1], line: Number(m[2]), col: Number(m[3]), severity: m[4] === 'warning' ? 'warning' : 'error', message: m[5] } : null;
}

async function gitInfo(dir: string): Promise<{ sha: string; dirty: boolean }> {
  const sha = await run('git', ['-C', dir, 'rev-parse', 'HEAD']);
  const status = await run('git', ['-C', dir, 'status', '--porcelain']);
  return { sha: sha.code === 0 ? sha.stdout.trim() : 'unknown', dirty: status.stdout.trim().length > 0 };
}

function spawnLogged(cmd: string, args: string[], env: Record<string, string>, cwd: string, ctx: JobCtx, onLine: (l: string) => void): Promise<number> {
  return new Promise((resolve) => {
    const child = spawn(cmd, args, { env, cwd, stdio: ['ignore', 'pipe', 'pipe'] });
    const abort = () => child.kill('SIGTERM');
    ctx.signal.addEventListener('abort', abort, { once: true });
    const pump = (stream: NodeJS.ReadableStream, name: 'out' | 'err') => {
      let buf = '';
      stream.on('data', (d: Buffer) => {
        buf += d.toString();
        let i: number;
        while ((i = buf.indexOf('\n')) >= 0) {
          const line = stripAnsi(buf.slice(0, i)).replace(/\r$/, '');
          buf = buf.slice(i + 1);
          ctx.log(line, name);
          onLine(line);
        }
      });
      stream.on('end', () => buf && (ctx.log(stripAnsi(buf), name), onLine(stripAnsi(buf))));
    };
    pump(child.stdout!, 'out');
    pump(child.stderr!, 'err');
    child.on('close', (code) => {
      ctx.signal.removeEventListener('abort', abort);
      resolve(code ?? 1);
    });
    child.on('error', () => resolve(127));
  });
}

export interface BuildInput {
  sourceDir: string;
  profile: string;
  buildType: 'debug' | 'release';
  app: string;
  clean: boolean;
}

export async function runBuild(db: Db, ctx: JobCtx, inp: BuildInput) {
  const t0 = Date.now();
  const src = checkSourceDir(inp.sourceDir);
  ctx.stage('resolve');
  const prof = resolveProfile(src, inp.profile);
  if (prof.app !== inp.app) {
    throw new FrError('INCOMPATIBLE_PROFILE', `profile ${inp.profile} is for app ${prof.app}, not ${inp.app}`);
  }
  const lock = readIdfLock(src);
  const idf = await idfStatus(lock);
  ctx.stage('idf_env');
  const env = await idfEnv(idf);

  const appDir = join(src, 'firmware', 'apps', inp.app);
  const buildDir = join(appDir, 'build', `${inp.profile}-${inp.buildType}`);
  if (inp.clean) {
    rmSync(buildDir, { recursive: true, force: true });
  }
  const genDir = join(buildDir, 'fr_gen');
  mkdirSync(genDir, { recursive: true });
  writeFileSync(join(genDir, 'sdkconfig.board'), prof.fragment);

  // Layer order is part of the contract (spec 03 §3.7); sdkconfig.local only if it exists.
  const layers = [
    join(src, 'firmware', 'config', 'sdkconfig.framework'),
    join(appDir, 'sdkconfig.defaults'),
    join(genDir, 'sdkconfig.board'),
    join(src, 'firmware', 'config', `sdkconfig.build.${inp.buildType}`),
    join(src, 'firmware', 'config', 'sdkconfig.local'),
  ].filter((f) => existsSync(f));
  const layerHash = createHash('sha256')
    .update(layers.map((f) => f + '\n' + readFileSync(f, 'utf8')).join('\n---\n'))
    .digest('hex');
  const hashFile = join(buildDir, 'fr_layers.sha256');
  if (!existsSync(hashFile) || readFileSync(hashFile, 'utf8') !== layerHash) {
    rmSync(join(buildDir, 'sdkconfig'), { force: true });
    ctx.log('sdkconfig layers changed: regenerating sdkconfig', 'event');
  }

  ctx.stage('compile');
  const diagnostics: Diagnostic[] = [];
  // idf.py explains missing component requirements in a 3-line block ending in "To fix this, ...".
  const hints: string[] = [];
  let hintOpen = false;
  const args = [
    '-C', appDir,
    '-B', buildDir,
    `-DIDF_TARGET=${prof.target}`,
    `-DSDKCONFIG=${join(buildDir, 'sdkconfig')}`,
    `-DSDKCONFIG_DEFAULTS=${layers.join(';')}`,
    'build',
  ];
  const code = await spawnLogged('idf.py', args, env, src, ctx, (line) => {
    const d = parseDiagnostic(line);
    if (d && diagnostics.length < 50) {
      diagnostics.push(d);
    }
    if (/^Compilation failed because/.test(line)) {
      hintOpen = true;
      hints.push('');
    }
    if (hintOpen && hints.length <= 10) {
      hints[hints.length - 1] = `${hints[hints.length - 1]} ${line}`.trim();
      hintOpen = !/^To fix this/.test(line);
    }
    const pct = /^\[(\d+)\/(\d+)\]/.exec(line);
    if (pct) {
      ctx.progress(Math.round((100 * Number(pct[1])) / Number(pct[2])));
    }
  });
  if (code !== 0) {
    throw new FrError('BUILD_FAILED', `idf.py build failed (exit ${code})`, {
      ...(hints.length ? { hint: hints[0] } : {}),
      details: { diagnostics: diagnostics.filter((d) => d.severity === 'error').slice(0, 20), hints, build_dir: buildDir },
      remediation: [{ tool: 'job_logs', args: { job_id: ctx.jobId, errors_only: true } }],
    });
  }
  writeFileSync(hashFile, layerHash);

  ctx.stage('ingest');
  const previous = lastFwId(db, src, inp.profile, inp.buildType);
  const git = await gitInfo(src);
  const { manifest, manifestPath } = ingestBuild(db, {
    sourceDir: src,
    buildDir,
    app: inp.app,
    profile: inp.profile,
    buildType: inp.buildType,
    board: prof.board,
    target: prof.target,
    partProfile: prof.partProfile,
    git,
    idf: { version: lock.idf.tag, commit: idf.actual_commit ?? '' },
  });
  const slot = manifest.partitions.find((p) => p.label === 'ota_0');
  return {
    build_id: manifest.build_id,
    fw_id: manifest.fw_id,
    cache_hit: previous === manifest.fw_id,
    size: manifest.size,
    slot_pct: slot ? Math.round((1000 * manifest.size) / slot.size) / 10 : null,
    target: prof.target,
    board: prof.board,
    source_dir: src,
    git,
    manifest: manifestPath,
    duration_ms: Date.now() - t0,
    diagnostics,
  };
}
