// client_generate (design c6 §4, D11, D12, D16; spec 09 §9.4, 07 §7.9): an app project's typed device
// registry for @fractonica/sdk, from the live registry and the hub's catalog (no checkout needed). The
// files come back in the result and the caller writes them (`fr codegen client --out <dir>`):
// - devices.ts: each provisioned device's id, profile, board and capability instances, by alias, with the
//   hub's registry_rev and catalog_hash. No secrets: commit it. Deterministic (sorted, no timestamp), so
//   regenerating an unchanged registry changes nothing.
// - token.ts: the /app token (secret: written 0600, git-ignored, never printed; `fr mcp` redacts it).
// - .gitignore: token.ts.

import { FrError, type GeneratedFile } from '@fractonica/protocol';
import { CATALOG_HASH } from '@fractonica/protocol/gen';

import type { Device, HubContext, OpInput } from '../context.ts';
import { boardInstances, provisionedDevices, registryRev } from './directory.ts';
import { appTokenOf } from './token.ts';

export interface ClientDevice {
  alias: string;
  id: string;
  profile: string | null;
  board: string | null;
  /** Instance name -> capability, by port; null when the firmware's instances are unknown. */
  caps: { name: string; cap: string }[] | null;
}

/** Single-quoted TS string literal. */
function q(s: string): string {
  return `'${JSON.stringify(s).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;
}

/** A property key: bare when it is an identifier, quoted otherwise (aliases have dashes). */
function key(s: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s) ? s : q(s);
}

/** devices.ts: `export const devices = {...} as const` and its type; no imports. */
export function renderDevicesTs(devices: readonly ClientDevice[], rev: string, catalogHash: number): string {
  const sorted = [...devices].sort((a, b) => (a.alias < b.alias ? -1 : a.alias > b.alias ? 1 : 0));
  const lines = [
    `// GENERATED by fr codegen client from the hub's registry (registry_rev ${rev}). Do not edit; run`,
    '// `fr codegen client --out <this directory>` again after provisioning or renaming a device. No secrets:',
    '// commit it. The token is in token.ts (git-ignored); pages the hub serves get it injected instead.',
    '',
    'export const devices = {',
    `  catalogHash: 0x${catalogHash.toString(16).padStart(8, '0')},`,
    `  registryRev: ${q(rev)},`,
  ];
  if (sorted.length === 0) {
    lines.push('  devices: {},');
  } else {
    lines.push('  devices: {');
    for (const d of sorted) {
      const caps = (d.caps ?? []).map((c) => `${key(c.name)}: ${q(c.cap)}`).join(', ');
      lines.push(
        `    ${key(d.alias)}: { id: ${q(d.id)}, profile: ${d.profile === null ? 'null' : q(d.profile)}, board: ${d.board === null ? 'null' : q(d.board)}, caps: {${caps ? ` ${caps} ` : ''}} },`,
      );
    }
    lines.push('  },');
  }
  lines.push('} as const;', '', 'export type Devices = typeof devices;', '');
  return lines.join('\n');
}

/** token.ts: the /app token. */
export function renderTokenTs(token: string): string {
  return [
    '// GENERATED by fr codegen client: the hub\'s /app token (secrets.json app_token). Secret: git-ignored,',
    '// never commit or print it. Pass it to connect({ token }) from apps the hub does not serve.',
    '',
    `export const token = ${q(token)};`,
    '',
  ].join('\n');
}

function clientDevice(hub: HubContext, d: Device): ClientDevice {
  const caps = boardInstances(hub, d);
  return { alias: d.alias, id: d.device_id, profile: d.profile, board: d.board, caps: caps && caps.map((c) => ({ name: c.name, cap: c.cap })) };
}

export function clientGenerate(hub: HubContext, input: OpInput<'client_generate'>) {
  const all = provisionedDevices(hub);
  let devices = all;
  if (input.selector) {
    const ids = new Set(hub.registry.resolve(input.selector, (id) => hub.router.presence(id)).map((d) => d.device_id));
    devices = all.filter((d) => ids.has(d.device_id));
    if (!devices.length) {
      throw new FrError('NOT_FOUND', `no provisioned device matches ${JSON.stringify(input.selector)}`, {
        remediation: [{ tool: 'device_list', cli: 'fr devices ls' }],
      });
    }
  }
  const warnings: string[] = [];
  if (!all.length) {
    warnings.push('no provisioned device: devices.ts lists none (provision one, then generate again)');
  }
  const entries = devices.map((d) => clientDevice(hub, d));
  for (const e of entries) {
    if (e.caps === null) {
      warnings.push(`${e.alias}: its firmware's instances are unknown (not seen since the hub started, and no artifact of its fw_id): devices.ts lists none; generate again once it is online`);
    }
  }
  const rev = registryRev(hub);
  const files: GeneratedFile[] = [{ path: 'devices.ts', content: renderDevicesTs(entries, rev, CATALOG_HASH) }];
  if (input.token) {
    files.push({ path: 'token.ts', content: renderTokenTs(appTokenOf(hub)), secret: true });
  }
  files.push({ path: '.gitignore', content: 'token.ts\n' });
  return { files, registry_rev: rev, catalog_hash: CATALOG_HASH, devices: entries.length, warnings };
}
