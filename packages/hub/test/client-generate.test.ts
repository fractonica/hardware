// client_generate and `fr codegen client` (design c6 §4, D11, D12, D16; spec 09 §9.4): devices.ts from the
// provisioned devices (deterministic, importable, the hub's registry_rev and catalog_hash), token.ts
// marked secret, the selector and warnings; the token's creation in secrets.json; and the CLI writing the
// files under --out (token.ts 0600) without ever printing the token, against a real hub server on port 0.

import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import type { AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { afterEach, describe, expect, it } from 'vitest';

import { findOp, REGISTRY_HASH } from '@fractonica/protocol';
import { CATALOG_HASH } from '@fractonica/protocol/gen';

import { renderDevicesTs } from '../src/apps/client-gen.ts';
import { registryRev } from '../src/apps/directory.ts';
import { createAppServer } from '../src/apps/server.ts';
import { loadAppToken, tokenMatches } from '../src/apps/token.ts';
import type { HubContext, HubRunOptions, StaticSite, WsServer } from '../src/context.ts';
import { buildServer } from '../src/http.ts';
import { HANDLERS } from '../src/ops.ts';
import { type NetRig, netRig } from './fake-node.ts';

const MAIN = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'cli', 'src', 'main.ts');
const TOKEN = 'cg-token-0123456789abcdef0123456789abcdef';
const RUN: HubRunOptions = { apiHost: '127.0.0.1', apiPort: 0, nodeHost: '127.0.0.1', nodePort: 0, nodeHttpPort: 0, noAdvert: true, serial: false };
const NOOP: WsServer & StaticSite = { start() {}, stop() {}, routes() {}, dashboard: () => ({ url: '', built: false, stale: false }) };

const cleanups: (() => unknown)[] = [];
afterEach(async () => {
  for (const c of cleanups.splice(0).reverse()) {
    await c();
  }
});

function tmp(prefix: string): string {
  // Real path: the CLI resolves --out from its cwd, which macOS reports under /private/var.
  const dir = realpathSync(mkdtempSync(join(tmpdir(), prefix)));
  cleanups.push(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
}

/** Two pads online (boot button, status LED), one provisioned device never seen, one unprovisioned. */
async function rigWithPads(): Promise<{ r: NetRig; hub: HubContext }> {
  const r = await netRig();
  cleanups.push(() => r.close());
  const hub = { ...r.hub, appServer: createAppServer(() => hub, RUN, { token: TOKEN }), wsServer: NOOP, staticSite: NOOP } as HubContext;
  const c6 = r.pad({ mac: '58e6c5d55e64', addr: 0x12, alias: 'pad-c6' });
  const c3 = r.pad({ mac: '1cdbd4175cc4', addr: 0x11, alias: 'pad-c3' });
  await Promise.all([c6.connected(r.events, 10_000), c3.connected(r.events, 10_000)]);
  Object.assign(r.registry.get('58e6c5d55e64')!, { profile: 'c6-pad', board: 'esp32c6-supermini' });
  Object.assign(r.registry.get('1cdbd4175cc4')!, { profile: 'c3o-pad', board: 'esp32c3-oled042' });
  r.registry.add({ device_id: '1cdbd416ba34', alias: 'pad-c3b', provisioned: true, addr: 3, profile: 'c3o-pad', board: 'esp32c3-oled042' });
  r.registry.add({ device_id: 'aabbccddeeff', alias: 'stranger', provisioned: false });
  return { r, hub };
}

const generate = async (hub: HubContext, input: Record<string, unknown> = {}) =>
  (await HANDLERS.client_generate(findOp('client_generate')!.input.parse(input), hub)) as {
    files: { path: string; content: string; secret?: true }[];
    registry_rev: string;
    catalog_hash: number;
    devices: number;
    warnings: string[];
  };

describe('client_generate', () => {
  it('renders devices.ts of the provisioned devices, token.ts (secret) and .gitignore', async () => {
    const { hub } = await rigWithPads();
    const g = await generate(hub);
    expect(g.files.map((f) => [f.path, f.secret ?? false])).toEqual([
      ['devices.ts', false],
      ['token.ts', true],
      ['.gitignore', false],
    ]);
    expect(g).toMatchObject({ registry_rev: registryRev(hub), catalog_hash: CATALOG_HASH, devices: 3 });
    const devices = g.files[0].content;
    expect(devices).toBe(
      [
        `// GENERATED by fr codegen client from the hub's registry (registry_rev ${g.registry_rev}). Do not edit; run`,
        '// `fr codegen client --out <this directory>` again after provisioning or renaming a device. No secrets:',
        '// commit it. The token is in token.ts (git-ignored); pages the hub serves get it injected instead.',
        '',
        'export const devices = {',
        `  catalogHash: 0x${CATALOG_HASH.toString(16)},`,
        `  registryRev: '${g.registry_rev}',`,
        '  devices: {',
        "    'pad-c3': { id: '1cdbd4175cc4', profile: 'c3o-pad', board: 'esp32c3-oled042', caps: { boot: 'fr.button', status: 'fr.led' } },",
        "    'pad-c3b': { id: '1cdbd416ba34', profile: 'c3o-pad', board: 'esp32c3-oled042', caps: {} },",
        "    'pad-c6': { id: '58e6c5d55e64', profile: 'c6-pad', board: 'esp32c6-supermini', caps: { boot: 'fr.button', status: 'fr.led' } },",
        '  },',
        '} as const;',
        '',
        'export type Devices = typeof devices;',
        '',
      ].join('\n'),
    );
    expect(devices).not.toContain(TOKEN);
    expect(g.files[1].content).toContain(`export const token = '${TOKEN}';`);
    expect(g.files[2].content).toBe('token.ts\n');
    expect(g.warnings).toEqual([expect.stringMatching(/^pad-c3b: its firmware's instances are unknown/)]);
    // Deterministic: the same registry renders the same bytes.
    expect((await generate(hub)).files[0].content).toBe(devices);
  });

  it('takes a selector (the registry_rev stays the whole registry\'s) and token: false; NOT_FOUND for no provisioned match', async () => {
    const { hub } = await rigWithPads();
    const g = await generate(hub, { selector: 'pad-c6', token: false });
    expect(g.files.map((f) => f.path)).toEqual(['devices.ts', '.gitignore']);
    expect(g.devices).toBe(1);
    expect(g.registry_rev).toBe(registryRev(hub));
    expect(g.files[0].content).toContain("'pad-c6': {");
    expect(g.files[0].content).not.toContain("'pad-c3'");
    await expect(generate(hub, { selector: 'stranger' })).rejects.toMatchObject({ code: 'NOT_FOUND' });
  });

  it('writes an importable module the SDK takes as its registry', async () => {
    const { hub } = await rigWithPads();
    const dir = tmp('fr-cg-');
    writeFileSync(join(dir, 'devices.ts'), (await generate(hub)).files[0].content);
    const mod = (await import(join(dir, 'devices.ts'))) as { devices: { catalogHash: number; registryRev: string; devices: Record<string, { id: string; caps: Record<string, string> }> } };
    expect(mod.devices.catalogHash).toBe(CATALOG_HASH);
    expect(mod.devices.registryRev).toBe(registryRev(hub));
    expect(mod.devices.devices['pad-c6']).toEqual({ id: '58e6c5d55e64', profile: 'c6-pad', board: 'esp32c6-supermini', caps: { boot: 'fr.button', status: 'fr.led' } });
  });

  it('registry_rev changes with a rename and a provisioning, not with presence', async () => {
    const { r, hub } = await rigWithPads();
    const rev = registryRev(hub);
    expect(registryRev(hub)).toBe(rev);
    r.registry.update('58e6c5d55e64', { alias: 'pad-blue' });
    const renamed = registryRev(hub);
    expect(renamed).not.toBe(rev);
    r.registry.add({ device_id: '0a0b0c0d0e0f', alias: 'pad-new', provisioned: true, addr: 9 });
    expect(registryRev(hub)).not.toBe(renamed);
    expect(renderDevicesTs([], '00000000', 1)).toContain('  devices: {},');
  });
});

describe('the /app token (D11)', () => {
  it('is created in secrets.json (0600, other secrets kept), then read back; compared in constant time', () => {
    const dir = tmp('fr-home-');
    const file = join(dir, 'secrets.json');
    writeFileSync(file, JSON.stringify({ wifi_password: 'keep-me' }), { mode: 0o600 });
    const t = loadAppToken(file);
    expect(t).toMatch(/^[A-Za-z0-9_-]{43}$/);
    const saved = JSON.parse(readFileSync(file, 'utf8')) as Record<string, string>;
    expect(saved).toEqual({ wifi_password: 'keep-me', app_token: t });
    expect(statSync(file).mode & 0o777).toBe(0o600);
    expect(loadAppToken(file)).toBe(t);
    const fresh = join(dir, 'nested', 'secrets.json');
    expect(loadAppToken(fresh)).not.toBe(t);
    expect(existsSync(fresh)).toBe(true);
    expect(tokenMatches(t, t)).toBe(true);
    expect(tokenMatches(t, `${t}x`)).toBe(false);
    expect(tokenMatches(t, 42)).toBe(false);
    writeFileSync(join(dir, 'bad.json'), '{not json');
    expect(() => loadAppToken(join(dir, 'bad.json'))).toThrow(expect.objectContaining({ code: 'ENV_MISSING' }));
  });
});

// The CLI as a subprocess against a hub server on port 0 (FR_HUB), never the lab's.
describe('fr codegen client', { timeout: 60_000 }, () => {
  function fr(args: string[], hub: string, cwd: string): Promise<{ code: number | null; stdout: string; stderr: string }> {
    return new Promise((res) => {
      const child = spawn(process.execPath, ['--conditions=@fractonica/source', MAIN, ...args], { env: { ...process.env, FR_HUB: hub }, cwd, stdio: ['ignore', 'pipe', 'pipe'] });
      let stdout = '';
      let stderr = '';
      child.stdout.on('data', (c: Buffer) => (stdout += c));
      child.stderr.on('data', (c: Buffer) => (stderr += c));
      child.on('close', (code) => res({ code, stdout, stderr }));
    });
  }

  it('writes devices.ts, token.ts (0600) and .gitignore under --out, never printing the token', async () => {
    const { hub } = await rigWithPads();
    const app = buildServer(hub, 0);
    cleanups.push(() => app.close());
    await app.listen({ host: '127.0.0.1', port: 0 });
    const url = `http://127.0.0.1:${(app.server.address() as AddressInfo).port}`;
    const cwd = tmp('fr-cg-cwd-');
    const human = await fr(['codegen', 'client', '--out', 'game/fractonica'], url, cwd);
    expect(human.code, human.stderr).toBe(0);
    const out = join(cwd, 'game', 'fractonica');
    expect(human.stdout).toContain(`wrote ${join(out, 'devices.ts')} (3 devices, registry_rev ${registryRev(hub)})`);
    expect(human.stdout).toContain('token.ts (secret, mode 0600, git-ignored)');
    expect(human.stderr).toContain('warning: pad-c3b:');
    expect(readFileSync(join(out, 'devices.ts'), 'utf8')).toContain("'pad-c6': { id: '58e6c5d55e64'");
    expect(readFileSync(join(out, 'token.ts'), 'utf8')).toContain(TOKEN);
    expect(statSync(join(out, 'token.ts')).mode & 0o777).toBe(0o600);
    expect(readFileSync(join(out, '.gitignore'), 'utf8')).toBe('token.ts\n');
    expect(human.stdout + human.stderr).not.toContain(TOKEN);

    // --json: what was written, devices.ts' content, never token.ts' content. A token.ts already there with a
    // wider mode is narrowed to 0600.
    mkdirSync(join(cwd, 'fractonica'));
    writeFileSync(join(cwd, 'fractonica', 'token.ts'), 'old\n', { mode: 0o644 });
    const json = await fr(['codegen', 'client', '--json'], url, cwd);
    expect(statSync(join(cwd, 'fractonica', 'token.ts')).mode & 0o777).toBe(0o600);
    expect(readFileSync(join(cwd, 'fractonica', 'token.ts'), 'utf8')).toContain(TOKEN);
    expect(json.code, json.stderr).toBe(0);
    expect(json.stdout).not.toContain(TOKEN);
    const r = JSON.parse(json.stdout) as { ok: boolean; data: { out: string; files: { path: string; secret?: true; content?: string }[]; registry_rev: string } };
    expect(r.ok).toBe(true);
    expect(r.data.out).toBe(join(cwd, 'fractonica'));
    expect(r.data.files.find((f) => f.path === 'token.ts')).toEqual({ path: 'token.ts', written: join(cwd, 'fractonica', 'token.ts'), bytes: expect.any(Number), secret: true });
    expect(r.data.files.find((f) => f.path === 'devices.ts')?.content).toContain('export const devices');

    // --no-token, and a selector the hub refuses (NOT_FOUND, exit 3, nothing written).
    const cwd2 = tmp('fr-cg-cwd2-');
    expect((await fr(['codegen', 'client', '--no-token', '--selector', 'pad-c3'], url, cwd2)).code).toBe(0);
    expect(existsSync(join(cwd2, 'fractonica', 'token.ts'))).toBe(false);
    expect(readFileSync(join(cwd2, 'fractonica', 'devices.ts'), 'utf8')).toContain("'pad-c3': {");
    const none = await fr(['codegen', 'client', '--selector', 'stranger', '--out', 'x'], url, cwd2);
    expect(none.code).not.toBe(0);
    expect(none.stderr).toContain('NOT_FOUND');
    expect(existsSync(join(cwd2, 'x'))).toBe(false);
  });

  it('writes nothing for a reply with a path outside --out', async () => {
    const server = createServer((req, res) => {
      if (req.url === '/api/v1/health') {
        res.end(JSON.stringify({ ok: true, version: 'test', registry_hash: REGISTRY_HASH, pid: 1 }));
        return;
      }
      res.end(JSON.stringify({ ok: true, cursor: 'c:1.1', data: { files: [{ path: '../evil.ts', content: 'x' }], registry_rev: '00000000', catalog_hash: 1, devices: 0, warnings: [] } }));
    });
    await new Promise<void>((r) => server.listen(0, '127.0.0.1', r));
    cleanups.push(() => new Promise<void>((r) => server.close(() => r())));
    const cwd = tmp('fr-cg-evil-');
    const r = await fr(['codegen', 'client', '--out', 'out'], `http://127.0.0.1:${(server.address() as AddressInfo).port}`, cwd);
    expect(r.code).not.toBe(0);
    expect(r.stderr).toContain('will not write');
    expect(existsSync(join(cwd, 'out'))).toBe(false);
    expect(existsSync(join(cwd, 'evil.ts'))).toBe(false);
  });
});
