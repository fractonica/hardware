// ---- JSON Schemas ----

type Schema = Record<string, unknown>;

function u64Schema(range?: [number, number]): Schema {
  return {
    anyOf: [
      { type: 'integer', minimum: range ? range[0] : 0, maximum: range ? Math.min(range[1], Number.MAX_SAFE_INTEGER) : Number.MAX_SAFE_INTEGER },
      { type: 'string', pattern: '^(0|[1-9][0-9]{0,19})$' },
    ],
  };
}

function elementSchema(el: ElementType): Schema {
  if (el.kind === 'struct') {
    return objectSchema(el.def.fields);
  }
  if (el.kind === 'enum') {
    return { type: 'string', enum: el.def.members.map((m) => m.name) };
  }
  return scalarSchema(el.name);
}

function scalarSchema(name: ScalarName, range?: [number, number]): Schema {
  switch (catOf(name)) {
    case 'bool':
      return { type: 'boolean' };
    case 'f32': {
      if (!range) {
        return { type: 'number' };
      }
      const [lo, hi] = f32Range(range);
      return { type: 'number', minimum: lo, maximum: hi };
    }
    case 'u64':
      return u64Schema(range);
    default: {
      const b = scalarBounds(name)!;
      return { type: 'integer', minimum: range ? range[0] : Number(b.min), maximum: range ? range[1] : Number(b.max) };
    }
  }
}

function fieldSchema(f: Field): Schema {
  const t = f.type;
  let s: Schema;
  switch (t.kind) {
    case 'scalar':
      s = scalarSchema(t.name, f.range);
      if (zeroExempt(f)) {
        // 0 is the absent field (design c2 §3), so the accessors take it and decoders print it.
        s = { anyOf: [t.name === 'u64' ? { enum: [0, '0'] } : { const: 0 }, s] };
      }
      break;
    case 'enum':
      s = { type: 'string', enum: t.def.members.map((m) => m.name) };
      break;
    case 'string':
      // maxLength counts characters; the codec limit is UTF-8 bytes, which encodeMember enforces.
      s = { type: 'string', maxLength: t.max };
      break;
    case 'bytes':
      s = { type: 'string', pattern: `^([0-9a-fA-F]{2}){0,${t.max}}$`, contentEncoding: 'base16' };
      break;
    case 'array':
      s = { type: 'array', maxItems: t.max, items: elementSchema(t.element) };
      break;
  }
  const description = fieldDoc({ ...f, default: undefined });
  return { ...s, ...(description ? { description } : {}), ...(f.default !== undefined ? { default: f.default } : {}) };
}

function objectSchema(fields: readonly Field[]): Schema {
  return { type: 'object', properties: Object.fromEntries(fields.map((f) => [f.name, fieldSchema(f)])), additionalProperties: false };
}

function memberSchema(id: string, title: string, description: string | undefined, fields: readonly Field[], examples: readonly unknown[]): Schema {
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `urn:fractonica:schema:${id}`,
    title,
    ...(description ? { description: description.trim() } : {}),
    ...objectSchema(fields),
    ...(examples.length > 0 ? { examples } : {}),
  };
}

function emitSchemas(model: Model, names: Names): GeneratedFile[] {
  const schemas: [string, Schema][] = [];
  for (const cap of model.capabilities) {
    for (const cmd of cap.commands) {
      const key = `${cap.name}.${cmd.name}.args`;
      schemas.push([key, memberSchema(key, `${cap.name}.${cmd.name} arguments`, cmd.doc, cmd.fields, cmd.examples)]);
    }
    for (const ev of cap.events) {
      const key = `${cap.name}.${ev.name}.event`;
      schemas.push([key, memberSchema(key, `${cap.name}.${ev.name} event`, ev.doc, ev.fields, [])]);
    }
  }
  const files: GeneratedFile[] = schemas.map(([key, s]) => ({ path: `${TS_GEN_DIR}/schemas/${key}.json`, content: `${JSON.stringify(s, null, 2)}\n` }));
  const c = new Code();
  c.block(header('schema/capabilities/*.cap.yaml', 'JSON Schemas (draft 2020-12) of every command\'s args and every event, as in gen/schemas/*.json.').trimEnd());
  c.line();
  c.line('export type JsonSchema = Readonly<Record<string, unknown>>;');
  c.line();
  c.open('export const JSON_SCHEMAS: Readonly<Record<string, JsonSchema>> = {');
  for (const [key, s] of schemas) {
    c.line(`${q(key)}: ${JSON.stringify(s)},`);
  }
  c.close('};');
  c.line();
  c.line("/** The schema of a command's args or an event's fields: jsonSchema('fr.led', 'args', 'blink'). */");
  c.open("export function jsonSchema(cap: string, part: 'args' | 'event', member: string): JsonSchema | undefined {");
  c.line('return JSON_SCHEMAS[`${cap}.${member}.${part}`];');
  c.close();
  for (const n of ['JsonSchema', 'JSON_SCHEMAS', 'jsonSchema']) {
    names.claim(n, 'schemas');
  }
  files.push({ path: `${TS_GEN_DIR}/schemas.ts`, content: c.toString() });
  return files;
}

function emitIndex(): GeneratedFile {
  const c = new Code();
  c.block(header('schema/*.yaml', 'Generated protocol and capability codecs (design c2 §2); ../wire is the runtime they build on.').trimEnd());
  c.line();
  c.line(
    "export type { CapCommandInfo, CapEventInfo, CapInfo, CapPropertyInfo, CapRequires, Codec, Encoded, JsonField, MemberPart, MemberRef, MessageInfo, StructInfo } from './support.ts';",
  );
  c.line("export { decodeJson, encodeJson } from './support.ts';");
  for (const m of ['caps/index', 'catalog', 'envelope', 'messages', 'protocol', 'schemas', 'serial']) {
    c.line(`export * from './${m}.ts';`);
  }
  return { path: `${TS_GEN_DIR}/index.ts`, content: c.toString() };
}

/** Every file under packages/protocol/src/gen, in a stable order. */
export function emitTs(model: Model): GeneratedFile[] {
  const shortNames = new Map<string, string>();
  for (const cap of model.capabilities) {
    const other = shortNames.get(cap.shortName);
    if (other) {
      throw new Error(`${cap.file}: ${cap.name} and ${other} would both generate caps/${cap.shortName}.ts`);
    }
    shortNames.set(cap.shortName, cap.name);
  }
  const names = new Names();
  for (const n of ['CapCommandInfo', 'CapEventInfo', 'CapInfo', 'CapPropertyInfo', 'CapRequires', 'Codec', 'Encoded', 'JsonField', 'MemberPart', 'MemberRef', 'MessageInfo', 'StructInfo', 'decodeJson', 'encodeJson']) {
    names.claim(n, 'support');
  }
  const files = [
    emitSupport(),
    emitProtocol(model, names),
    emitEnvelope(model, names),
    emitSerial(model, names),
    emitMessages(model, names),
    ...model.capabilities.map((cap) => emitCap(model, cap, names)),
    emitCapsIndex(model, names),
    ...emitCatalog(model, names),
    ...emitSchemas(model, names),
    emitIndex(),
  ];
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}
