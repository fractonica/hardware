/**
 * Names @fractonica/protocol already exports by hand (wire runtime, hub types). The generated codecs
 * are a separate entry point (`@fractonica/protocol/gen`, so a broken gen/ cannot stop `fr gen` from
 * loading), but consumers import from both: a generated system message type that would collide gets a
 * `Msg` suffix (LOG.LINE -> LogLineMsg).
 */
const HAND_WRITTEN_NAMES: ReadonlySet<string> = new Set([
  'ArtifactManifest', 'ClassPrefix', 'Cursor', 'Decoded', 'DecodeError', 'Envelope', 'ErrorCode', 'FrError', 'Header', 'Job', 'LogLine',
  'OpDef', 'OpKind', 'OpName', 'PortInfo', 'Reader', 'Remediation', 'Result', 'ToolError', 'Writer',
]);

// ---- code builder ----

class Code {
  private readonly out: string[] = [];
  private depth = 0;

  line(s = ''): this {
    this.out.push(s === '' ? '' : '  '.repeat(this.depth) + s);
    return this;
  }

  open(s: string): this {
    this.line(s);
    this.depth++;
    return this;
  }

  close(s = '}'): this {
    this.depth--;
    this.line(s);
    return this;
  }

  /** Ends a `case` body, which has no closing brace. */
  dedent(): this {
    this.depth--;
    return this;
  }

  /** A multi-line block (no trailing newline) at the current depth. */
  block(text: string): this {
    for (const l of text.split('\n')) {
      this.line(l);
    }
    return this;
  }

  toString(): string {
    return `${this.out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
  }
}

/** Single-quoted JS string literal. */
function q(s: string): string {
  return `'${JSON.stringify(s).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;
}

/** Integer literal; masks and large bounds in hex. */
function num(n: number): string {
  return Number.isInteger(n) && n > 0xffff ? `0x${n.toString(16)}` : String(n);
}

/** 0x0002-style literal for ids and addresses. */
function hex4(n: number): string {
  return `0x${n.toString(16).padStart(4, '0')}`;
}

/** A label for error messages: a template literal when it interpolates `path` or `i`. */
function lit(label: string): string {
  return label.includes('${') ? `\`${label}\`` : q(label);
}

function doc(c: Code, text: string | undefined): void {
  if (!text) {
    return;
  }
  const lines = text.trim().replace(/\*\//g, '*\\/').split('\n');
  if (lines.length === 1) {
    c.line(`/** ${lines[0]} */`);
  } else {
    c.line('/**');
    for (const l of lines) {
      c.line(l ? ` * ${l}` : ' *');
    }
    c.line(' */');
  }
}

function upperSnake(snake: string): string {
  return snake.toUpperCase();
}

function header(src: string, about: string): string {
  return `// GENERATED by fr gen from ${src}. Do not edit; run \`fr gen\`.\n// ${about}\n`;
}

// ---- types ----

type Cat = 'bool' | 'uint' | 'sint' | 'u64' | 'f32';

function catOf(name: ScalarName): Cat {
  if (name === 'bool' || name === 'u64' || name === 'f32') {
    return name;
  }
  return isSigned(name) ? 'sint' : 'uint';
}

/** Resolves enum identifiers within one generated module. */
interface Ctx {
  enumName(def: EnumDef): string;
  enumNames(def: EnumDef): string;
}

const UNDERLYING_MAX = { u8: 0xff, u16: 0xffff, u32: 0xffffffff } as const;

// Enums are open, as in the C++ codecs: a value the schema does not name decodes as its number, and
// only the JSON accessors (like C++ dispatch) reject it.
function tsType(t: TypeRef | ElementType, ctx: Ctx): string {
  switch (t.kind) {
    case 'scalar':
      return t.name === 'bool' ? 'boolean' : t.name === 'u64' ? 'bigint' : 'number';
    case 'enum':
      return `${ctx.enumName(t.def)} | number`;
    case 'struct':
      return t.def.name;
    case 'string':
      return 'string';
    case 'bytes':
      return 'Uint8Array';
    case 'array':
      return t.element.kind === 'enum' ? `(${tsType(t.element, ctx)})[]` : `${tsType(t.element, ctx)}[]`;
  }
}

function zeroMember(def: EnumDef, where: string): string {
  const m = def.members.find((x) => x.value === 0);
  if (!m) {
    throw new Error(`${where}: enum ${def.name} has no member with value 0; give the field a default`);
  }
  return m.name;
}

/** The type's integer bounds as TS literals (bigint literals for u64). */
function intBounds(name: ScalarName): [string, string] {
  const b = scalarBounds(name)!;
  if (name === 'u64') {
    return [`${b.min}n`, `${b.max}n`];
  }
  return [num(Number(b.min)), num(Number(b.max))];
}

function scalarLit(t: TypeRef, v: JsonScalar): string {
  if (t.kind === 'enum' || t.kind === 'string') {
    return q(String(v));
  }
  if (t.kind === 'scalar') {
    if (t.name === 'bool') {
      return String(v);
    }
    if (t.name === 'u64') {
      return `${BigInt(v)}n`;
    }
    return num(Number(v));
  }
  throw new Error(`no scalar literal for ${t.kind}`);
}

/** The value an absent implicit field decodes to; `fresh` builds new objects for mutable defaults. */
function zeroLit(t: TypeRef, where: string, fresh: boolean): string {
  switch (t.kind) {
    case 'scalar':
      return t.name === 'bool' ? 'false' : t.name === 'u64' ? '0n' : '0';
    case 'enum':
      return q(zeroMember(t.def, where));
    case 'string':
      return "''";
    case 'bytes':
      return fresh ? 'new Uint8Array(0)' : '$.EMPTY';
    case 'array':
      return '[]';
  }
}

function defaultLit(f: Field, where: string, fresh: boolean): string {
  return f.default !== undefined ? scalarLit(f.type, f.default) : zeroLit(f.type, where, fresh);
}

function fieldDoc(f: { doc?: string; unit?: string; range?: [number, number]; default?: JsonScalar; type: TypeRef }): string | undefined {
  const facts: string[] = [];
  if (f.unit) {
    facts.push(f.unit);
  }
  if (f.range) {
    facts.push(`${f.range[0]}..${f.range[1]}`);
  }
  if (f.type.kind === 'string' || f.type.kind === 'bytes' || f.type.kind === 'array') {
    facts.push(f.type.kind === 'string' ? `<= ${f.type.max} UTF-8 bytes` : f.type.kind === 'bytes' ? `<= ${f.type.max} bytes` : `<= ${f.type.max} items`);
  }
  if (f.default !== undefined) {
    facts.push(`default ${typeof f.default === 'string' ? f.default : JSON.stringify(f.default)}`);
  }
  const text = [f.doc?.trim().replace(/\s+/g, ' '), facts.length > 0 ? `(${facts.join('; ')})` : ''].filter((s) => s).join(' ');
  return text || undefined;
}

// ---- worst-case size ----

function valueWireMax(t: TypeRef | ElementType): number {
  switch (t.kind) {
    case 'scalar': {
      if (t.name === 'f32') {
        return 4;
      }
      const b = scalarBounds(t.name)!;
      const zz = (v: bigint) => (v >= 0n ? v * 2n : -v * 2n - 1n);
      return varintSize(isSigned(t.name) ? (zz(b.min) > zz(b.max) ? zz(b.min) : zz(b.max)) : b.max);
    }
    case 'enum':
      return varintSize(UNDERLYING_MAX[t.def.underlying]);
    case 'string':
    case 'bytes':
      return varintSize(t.max) + t.max;
    case 'struct':
      return wireMax(t.def.fields);
    case 'array':
      throw new Error('arrays are sized per field');
  }
}

/**
 * Worst case over every value the field types can carry (any enum value, ignoring `range`), so any
 * decoded value re-encodes within it. The model's sizes use `range` and are what the budget checks.
 */
function wireMax(fields: readonly Field[]): number {
  let n = 0;
  for (const f of fields) {
    const t = f.type;
    if (t.kind === 'array') {
      const el = valueWireMax(t.element);
      if (t.element.kind === 'struct') {
        n += t.max * (tagSize(f.id) + varintSize(el) + el);
      } else {
        n += tagSize(f.id) + varintSize(t.max * el) + t.max * el;
      }
    } else {
      n += tagSize(f.id) + valueWireMax(t);
    }
  }
  return n;
}

// ---- encode ----

/** Checks `x` against the field's type (not its `range`); the result is what the writer takes (bytes for strings). */
function checkExpr(t: TypeRef | ElementType, x: string, label: string, ctx: Ctx): string {
  const L = lit(label);
  switch (t.kind) {
    case 'scalar':
      switch (catOf(t.name)) {
        case 'bool':
          return `$.bool(${x}, ${L})`;
        case 'f32':
          return `$.f32(${x}, ${L})`;
        case 'u64': {
          const [lo, hi] = intBounds(t.name);
          return `$.u64(${x}, ${lo}, ${hi}, ${L})`;
        }
        default: {
          const [lo, hi] = intBounds(t.name);
          return `$.int(${x}, ${lo}, ${hi}, ${L})`;
        }
      }
    case 'enum':
      return `$.enumValue(${ctx.enumName(t.def)}, ${x}, ${L}, ${num(UNDERLYING_MAX[t.def.underlying])})`;
    case 'string':
      return `$.str(${x}, ${t.max}, ${L})`;
    case 'bytes':
      return `$.bytes(${x}, ${t.max}, ${L})`;
    case 'array':
      return `$.list(${x}, ${t.max}, ${L})`;
    case 'struct':
      return `$.obj(${x}, ${L})`;
  }
}

function writeCall(t: TypeRef, id: number, x: string): string {
  switch (t.kind) {
    case 'scalar':
      switch (catOf(t.name)) {
        case 'bool':
          return `w.fieldBool(${id}, ${x})`;
        case 'f32':
          return `w.fieldF32(${id}, ${x})`;
        case 'u64':
          return `w.fieldUint64(${id}, ${x})`;
        case 'sint':
          return `w.fieldSint(${id}, ${x})`;
        default:
          return `w.fieldUint(${id}, ${x})`;
      }
    case 'enum':
      return `w.fieldUint(${id}, ${x})`;
    case 'string':
    case 'bytes':
      return `w.fieldBytes(${id}, ${x})`;
    case 'array':
      throw new Error('arrays are written element by element');
  }
}

/** One packed element (no tag). */
function writeElement(el: ElementType, x: string, label: string, ctx: Ctx): string {
  if (el.kind === 'struct') {
    throw new Error('struct elements are repeated, not packed');
  }
  const chk = checkExpr(el, x, label, ctx);
  if (el.kind === 'enum') {
    return `w.varint(${chk})`;
  }
  switch (catOf(el.name)) {
    case 'bool':
      return `w.varint(${chk} ? 1 : 0)`;
    case 'f32':
      return `w.f32(${chk})`;
    case 'u64':
      return `w.varint64(${chk})`;
    case 'sint':
      return `w.sint(${chk})`;
    default:
      return `w.varint(${chk})`;
  }
}

/** Whether the checked value `v` differs from the zero value (an f32 -0 has non-zero bits, as in C++). */
function nonZero(t: TypeRef, v: string): string {
  switch (t.kind) {
    case 'scalar':
      switch (catOf(t.name)) {
        case 'bool':
          return v;
        case 'f32':
          return `!Object.is(${v}, 0)`;
        case 'u64':
          return `${v} !== 0n`;
        default:
          return `${v} !== 0`;
      }
    case 'enum':
      return `${v} !== 0`;
    default:
      return `${v}.length > 0`;
  }
}

/**
 * Field presence (design c2 §3): `always` is written even when zero; `optional` is written iff set;
 * `implicit` is omitted when it equals its zero value.
 */
function emitEncodeField(c: Code, f: Field, src: string, label: string, where: string, ctx: Ctx): void {
  const t = f.type;
  const v = `f${f.id}`;
  if (t.kind === 'array') {
    const el = t.element;
    const elLabel = `${label}[\${i}]`;
    if (f.presence === 'optional') {
      if (el.kind === 'struct') {
        throw new Error(`${where}: an array of messages cannot be optional (an empty repeated field is absent)`);
      }
      c.open(`if (${src} !== undefined) {`);
      c.line(`const ${v} = ${checkExpr(t, src, label, ctx)};`);
    } else {
      c.open('{');
      c.line(`const ${v} = ${checkExpr(t, `${src} ?? []`, label, ctx)};`);
    }
    if (el.kind === 'struct') {
      c.open(`for (let i = 0; i < ${v}.length; i++) {`);
      c.line(`const m = w.beginLen(${f.id});`);
      c.line(`write${el.def.name}(w, ${v}[i], ${lit(elLabel)});`);
      c.line('w.endLen(m);');
      c.close();
    } else {
      // Packed: one length-delimited field. An optional array is written even when empty (present).
      c.open(f.presence === 'optional' ? '{' : `if (${v}.length > 0) {`);
      c.line(`const m = w.beginLen(${f.id});`);
      c.open(`for (let i = 0; i < ${v}.length; i++) {`);
      c.line(`${writeElement(el, `${v}[i]`, elLabel, ctx)};`);
      c.close();
      c.line('w.endLen(m);');
      c.close();
    }
    c.close();
    return;
  }
  if (f.presence === 'optional') {
    c.line(`if (${src} !== undefined) ${writeCall(t, f.id, checkExpr(t, src, label, ctx))};`);
    return;
  }
  if (f.presence === 'always') {
    c.line(`${writeCall(t, f.id, checkExpr(t, `${src} ?? ${defaultLit(f, where, false)}`, label, ctx))};`);
    return;
  }
  c.line(`const ${v} = ${checkExpr(t, `${src} ?? ${zeroLit(t, where, false)}`, label, ctx)};`);
  c.line(`if (${nonZero(t, v)}) ${writeCall(t, f.id, v)};`);
}

// ---- decode ----

/** Reads the current field: type bounds only; `range` and enum membership are the JSON accessors' checks. */
function readExpr(f: Field, ctx: Ctx): string {
  const t = f.type;
  switch (t.kind) {
    case 'scalar':
      switch (catOf(t.name)) {
        case 'bool':
          return 'r.readBool()';
        case 'f32':
          return 'r.readF32()';
        case 'u64':
          return 'r.readUint64()';
        case 'sint': {
          const [lo, hi] = intBounds(t.name);
          return `r.readSint(${lo}, ${hi})`;
        }
        default:
          return `r.readUint(${intBounds(t.name)[1]})`;
      }
    case 'enum':
      return `$.readEnum(r, ${ctx.enumNames(t.def)}, ${num(UNDERLYING_MAX[t.def.underlying])})`;
    case 'string':
      return `r.readString(${t.max})`;
    case 'bytes':
      return `r.readBytes(${t.max}).slice()`;
    case 'array': {
      const el = t.element;
      if (el.kind === 'struct') {
        throw new Error('repeated messages are read with readRepeated');
      }
      return `$.readPacked(r, ${t.max}, (p) => ${rawElement(el, ctx)})`;
    }
  }
}

function rawElement(el: Exclude<ElementType, { kind: 'struct' }>, ctx: Ctx): string {
  if (el.kind === 'enum') {
    return `$.rawEnum(p, ${ctx.enumNames(el.def)}, ${num(UNDERLYING_MAX[el.def.underlying])})`;
  }
  switch (catOf(el.name)) {
    case 'bool':
      return 'p.rawUint(1) === 1';
    case 'f32':
      return 'p.rawF32()';
    case 'u64':
      return 'p.rawUint64()';
    case 'sint': {
      const [lo, hi] = intBounds(el.name);
      return `p.rawSint(${lo}, ${hi})`;
    }
    default:
      return `p.rawUint(${intBounds(el.name)[1]})`;
  }
}

function initObject(fields: readonly Field[], where: string): string {
  const parts = fields.filter((f) => f.presence !== 'optional').map((f) => `${f.name}: ${defaultLit(f, `${where}.${f.name}`, true)}`);
  return parts.length > 0 ? `{ ${parts.join(', ')} }` : '{}';
}

function emitReadLoop(c: Code, fields: readonly Field[], ctx: Ctx): void {
  c.open('while (r.next()) {');
  c.open('switch (r.field) {');
  for (const f of fields) {
    c.open(`case ${f.id}:`);
    if (f.type.kind === 'array' && f.type.element.kind === 'struct') {
      c.line(`$.readRepeated(r, v.${f.name}, ${f.type.max}, read${f.type.element.def.name});`);
    } else {
      c.line(`v.${f.name} = ${readExpr(f, ctx)};`);
    }
    c.line('break;');
    c.dedent();
  }
  c.open('default:');
  c.line('r.skip();');
  c.dedent();
  c.close();
  c.close();
}

// ---- structs (interface + codec) ----

interface StructSpec {
  typeName: string;
  /** encode<Name>/decode<Name>. */
  fnName: string;
  fields: readonly Field[];
  where: string;
  doc?: string;
  /** Also emit write<Name>/read<Name> for use as a repeated element (protocol `types:`). */
  nested?: boolean;
}

function emitInterface(c: Code, s: StructSpec, ctx: Ctx): void {
  doc(c, s.doc);
  if (s.fields.length === 0) {
    c.line(`export type ${s.typeName} = Record<string, never>;`);
    c.line();
    return;
  }
  c.open(`export interface ${s.typeName} {`);
  for (const f of s.fields) {
    doc(c, fieldDoc(f));
    c.line(`${f.name}${f.presence === 'optional' ? '?' : ''}: ${tsType(f.type, ctx)};`);
  }
  c.close();
  c.line();
}

function emitStruct(c: Code, s: StructSpec, ctx: Ctx): void {
  emitInterface(c, s, ctx);
  if (s.nested) {
    // As an array element: written into the caller's length-delimited field, read from its sub-reader.
    c.open(`function write${s.typeName}(w: Writer, value: unknown, path: string): void {`);
    c.line(`const v = $.obj(value, path) as Partial<${s.typeName}>;`);
    for (const f of s.fields) {
      emitEncodeField(c, f, `v.${f.name}`, `\${path}.${f.name}`, `${s.where}.${f.name}`, ctx);
    }
    c.close();
    c.line();
    c.open(`function read${s.typeName}(r: Reader): ${s.typeName} {`);
    c.line(`const v: ${s.typeName} = ${initObject(s.fields, s.where)};`);
    emitReadLoop(c, s.fields, ctx);
    c.line('return v;');
    c.close();
    c.line();
    c.open(`export function encode${s.fnName}(v: Partial<${s.typeName}> = {}): Uint8Array {`);
    c.line('const w = new Writer();');
    c.line(`write${s.typeName}(w, v, ${q(snakeOf(s.typeName))});`);
    c.line('return w.finish();');
    c.close();
    c.line();
    c.open(`export function decode${s.fnName}(bytes: Uint8Array): Decoded<${s.typeName}> {`);
    c.line('const r = new Reader(bytes);');
    c.line(`return $.done(r, read${s.typeName}(r));`);
    c.close();
    c.line();
    return;
  }
  if (s.fields.length === 0) {
    c.open(`export function encode${s.fnName}(_v: Partial<${s.typeName}> = {}): Uint8Array {`);
    c.line('return new Uint8Array(0);');
    c.close();
    c.line();
    c.line('/** Unknown fields are skipped; malformed input is still an error. */');
    c.open(`export function decode${s.fnName}(bytes: Uint8Array): Decoded<${s.typeName}> {`);
    c.line('return $.decodeEmpty(bytes);');
    c.close();
    c.line();
    return;
  }
  c.line('/** Absent fields take their defaults; throws RangeError on a value the field type cannot carry. */');
  c.open(`export function encode${s.fnName}(v: Partial<${s.typeName}> = {}): Uint8Array {`);
  c.line('const w = new Writer();');
  for (const f of s.fields) {
    emitEncodeField(c, f, `v.${f.name}`, f.name, `${s.where}.${f.name}`, ctx);
  }
  c.line('return w.finish();');
  c.close();
  c.line();
  c.open(`export function decode${s.fnName}(bytes: Uint8Array): Decoded<${s.typeName}> {`);
  c.line('const r = new Reader(bytes);');
  c.line(`const v: ${s.typeName} = ${initObject(s.fields, s.where)};`);
  emitReadLoop(c, s.fields, ctx);
  c.line('return $.done(r, v);');
  c.close();
  c.line();
}

/** An f32 range as C++ compares it: bounds rounded to f32 (`0.1f`), so both reject the same values. */
function f32Range(range: [number, number]): [number, number] {
  return [Math.fround(range[0]), Math.fround(range[1])];
}

function jsonFieldsLit(fields: readonly Field[], ctx: Ctx): string {
  const one = (f: Field): string => {
    const t = f.type;
    const parts = [`name: ${q(f.name)}`];
    if (t.kind === 'bytes' || (t.kind === 'scalar' && t.name === 'u64') || (t.kind === 'array' && t.element.kind === 'scalar' && t.element.name === 'u64')) {
      parts.push(`json: '${t.kind === 'bytes' ? 'bytes' : 'u64'}'`);
    } else if (t.kind === 'array' && t.element.kind === 'struct') {
      parts.push(`json: ${upperSnake(snakeOf(t.element.def.name))}_JSON`);
    }
    const def = t.kind === 'enum' ? t.def : t.kind === 'array' && t.element.kind === 'enum' ? t.element.def : null;
    if (def) {
      parts.push(`members: ${ctx.enumName(def)}`);
    }
    if (f.range) {
      const [lo, hi] = t.kind === 'scalar' && t.name === 'f32' ? f32Range(f.range) : f.range;
      parts.push(`range: [${lo}, ${hi}]`);
      if (zeroExempt(f)) {
        parts.push('zeroExempt: true');
      }
    }
    return `{ ${parts.join(', ')} }`;
  };
  return `[${fields.map(one).join(', ')}]`;
}

function codecLit(s: StructSpec, ctx: Ctx): string {
  return `{ fields: ${jsonFieldsLit(s.fields, ctx)}, maxSize: ${wireMax(s.fields)}, encode: encode${s.fnName}, decode: decode${s.fnName} }`;
}

