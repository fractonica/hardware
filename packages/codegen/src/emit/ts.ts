// TS emitter for `fr gen` (design c2 §2-§4, spec 07 §7.6): packages/protocol/src/gen/** from the model.
// Typed codecs are unrolled per message on top of the hand-written wire runtime (packages/protocol/src/
// wire), one interface + encode + decode per system message and capability member, the way the C++
// emitter does it. The generic accessors (findCap, encodeMember, decodeMember, findMessage, ...) are
// table-driven over those codecs and speak the JSON form the hub and agents use: bytes as hex, u64 as a
// decimal string, enums by member name. Helpers the codecs share go to gen/support.ts, emitted verbatim.
//
// The codec rules are the C++ emitter's (cpp.ts), so both decoders accept and reject the same bytes:
// enums are open (an unnamed value decodes as its number) and `range` is not a codec check. The JSON
// accessors apply `range` and enum membership to the decoded value, defaults included, as C++ dispatch does.

