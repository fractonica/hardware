/**
 * Packed scalars in one length-delimited field; a repeated occurrence replaces the earlier one (last
 * wins). Element max+1 is too_long, reported before it is read.
 */
export function readPacked<T>(r: Reader, max: number, element: (p: Reader) => T): T[] {
  const p = r.readSub();
  const out: T[] = [];
  while (p.ok && !p.atEnd) {
    if (out.length === max) {
      p.fail('too_long');
      break;
    }
    const e = element(p);
    if (p.ok) {
      out.push(e);
    }
  }
  r.adopt(p);
  return out;
}

/** One element of a repeated message field (occurrences append); occurrence max+1 is too_long before it is read. */
export function readRepeated<T>(r: Reader, out: T[], max: number, element: (p: Reader) => T): void {
  if (out.length === max) {
    r.fail('too_long');
    return;
  }
  const p = r.readSub();
  if (!r.ok) {
    return;
  }
  const e = element(p);
  if (r.adopt(p)) {
    out.push(e);
  }
}

