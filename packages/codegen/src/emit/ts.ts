const HEX = '0123456789abcdef';

export function toHex(b: Uint8Array): string {
  let s = '';
  for (const x of b) {
    s += HEX[x >> 4] + HEX[x & 15];
  }
  return s;
}

export function fromHex(s: string, name: string): Uint8Array {
  if (!/^([0-9a-fA-F]{2})*$/.test(s)) {
    bad(name, 'an even-length hex string', s);
  }
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) {
    out[i] = parseInt(s.slice(2 * i, 2 * i + 2), 16);
  }
  return out;
}

function fromJsonValue(f: JsonField, v: unknown, name: string, lenient: boolean): unknown {
  if (f.members && !(lenient && typeof v === 'number')) {
    // The JSON Schema form, as C++ diag_json takes it: member names only.
    if (typeof v !== 'string' || !Object.hasOwn(f.members, v)) {
      bad(name, 'one of ' + Object.keys(f.members).join(', '), v);
    }
    return v;
  }
  if (f.json === 'bytes') {
    return typeof v === 'string' ? fromHex(v, name) : v;
  }
  if (f.json === 'u64') {
    if (typeof v === 'string' && /^[0-9]{1,20}$/.test(v)) {
      return BigInt(v);
    }
    return typeof v === 'number' && Number.isSafeInteger(v) ? BigInt(v) : v;
  }
  if (typeof f.json === 'object') {
    return fromJson(f.json, v, name, lenient);
  }
  return v;
}

/**
 * JSON form -> typed input: hex strings to bytes, decimal strings to u64, nested messages recursively.
 * As the JSON Schemas and C++ diag_json have it, enums are member names and a field is either a value or
 * left out: null throws RangeError (an undefined value or a null/undefined top-level value is absent), as
 * do unknown keys. lenient also takes an enum member as any number of its type (encodeJson(…, false)).
 * Other types are left to the typed encoder.
 */
export function fromJson(fields: readonly JsonField[], value: unknown, path = '', lenient = false): Record<string, unknown> {
  if (value === undefined || (value === null && path === '')) {
    return {};
  }
  const o = obj(value, path || 'value');
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(o)) {
    const f = fields.find((x) => x.name === k);
    const name = path ? path + '.' + k : k;
    if (!f) {
      throw new RangeError(name + ': unknown field (' + (fields.length > 0 ? 'fields: ' + fields.map((x) => x.name).join(', ') : 'no fields') + ')');
    }
    if (v === undefined) {
      continue;
    }
    if (v === null) {
      throw new RangeError(name + ': null is not a value (leave the field out)');
    }
    out[k] = Array.isArray(v) ? v.map((x, i) => fromJsonValue(f, x, name + '[' + i + ']', lenient)) : fromJsonValue(f, v, name, lenient);
  }
  return out;
}

/** Typed value -> JSON form (bytes as lowercase hex, bigint as a decimal string). */
export function toJson(v: unknown): unknown {
  if (v instanceof Uint8Array) {
    return toHex(v);
  }
  if (typeof v === 'bigint') {
    return v.toString();
  }
  if (Array.isArray(v)) {
    return v.map(toJson);
  }
  if (typeof v === 'object' && v !== null) {
    const out: Record<string, unknown> = {};
    for (const [k, x] of Object.entries(v)) {
      out[k] = toJson(x);
    }
    return out;
  }
  return v;
}

/**
 * The first 'range' or enum-membership violation in a typed value, or null; C++ valid() checks the same.
 * A NaN is outside every range; a zeroExempt field at 0 (an f32 -0 too, as in C++) is the absent field.
 */
export function invalid(fields: readonly JsonField[], value: Record<string, unknown>, path = ''): string | null {
  for (const f of fields) {
    const v = value[f.name];
    const name = path ? path + '.' + f.name : f.name;
    if (v === undefined) {
      continue;
    }
    if (typeof f.json === 'object') {
      const items = v as Record<string, unknown>[];
      for (let i = 0; i < items.length; i++) {
        const p = invalid(f.json, items[i], name + '[' + i + ']');
        if (p !== null) {
          return p;
        }
      }
      continue;
    }
    if (f.members) {
      const known = Object.values(f.members);
      const items = Array.isArray(v) ? v : [v];
      for (const x of items) {
        if (typeof x === 'number' && !known.includes(x)) {
          return name + ': ' + x + ' is not one of ' + Object.keys(f.members).join(', ');
        }
      }
    }
    if (f.range && (typeof v === 'number' || typeof v === 'bigint') && !(f.zeroExempt && (v === 0 || v === 0n)) && !(v >= f.range[0] && v <= f.range[1])) {
      return name + ': ' + v + ' is outside [' + f.range[0] + ', ' + f.range[1] + ']';
    }
  }
  return null;
}

/**
 * JSON form -> bytes. With validate (the default) the value as the receiver decodes it, defaults
 * applied, must keep every field in range and every enum value named, which is what C++ dispatch
 * checks (invalid_args); the codec itself carries both.
 */
export function encodeJson(codec: Codec<any>, value: unknown, validate = true): Encoded {
  try {
    const bytes = codec.encode(fromJson(codec.fields, value, '', !validate));
    if (validate) {
      const back = codec.decode(bytes);
      const problem = back.ok ? invalid(codec.fields, back.value) : back.error;
      if (problem !== null) {
        return { ok: false, error: 'invalid_args', detail: problem };
      }
    }
    return { ok: true, value: bytes };
  } catch (e) {
    if (e instanceof RangeError) {
      return { ok: false, error: 'invalid_args', detail: e.message };
    }
    throw e;
  }
}

/** Bytes -> JSON form. With validate (the default) a range or enum violation, defaults included, is out_of_range. */
export function decodeJson(codec: Codec<any>, bytes: Uint8Array, validate = true): Decoded<Record<string, unknown>> {
  const d = codec.decode(bytes);
  if (!d.ok) {
    return d;
  }
  if (validate && invalid(codec.fields, d.value) !== null) {
    return decodeFail('out_of_range');
  }
  return decodeOk(toJson(d.value) as Record<string, unknown>);
}

export function notFound(what: string): Encoded {
  return { ok: false, error: 'not_found', detail: what + ' not found' };
}

