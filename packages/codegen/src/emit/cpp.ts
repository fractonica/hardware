const SCALAR_CPP: Record<ScalarName, string> = {
  bool: 'bool',
  u8: 'uint8_t',
  u16: 'uint16_t',
  u32: 'uint32_t',
  u64: 'uint64_t',
  i8: 'int8_t',
  i16: 'int16_t',
  i32: 'int32_t',
  f32: 'float',
  rgb: 'uint32_t',
  duration_ms: 'uint32_t',
};

const UNDERLYING_CPP = { u8: 'uint8_t', u16: 'uint16_t', u32: 'uint32_t' } as const;
const LAYOUT_BYTES = { u8: 1, u16: 2, u32: 4 } as const;
const UINT_MAX_VAL = { u8: 0xff, u16: 0xffff, u32: 0xffffffff } as const;

/** 'fr.analog_in' -> 'AnalogIn' */
function capPascal(capName: string): string {
  return pascalCase(capName.slice(capName.lastIndexOf('.') + 1));
}

function enumCpp(def: EnumDef): string {
  return def.scope === 'protocol' ? def.name : `${capPascal(def.scope)}${def.name}`;
}

/** A message type's C++ struct: protocol types by name, a capability's prefixed like its enums (DisplayUiLayout). */
function structCpp(def: StructDef): string {
  return def.scope === 'protocol' ? def.name : `${capPascal(def.scope)}${def.name}`;
}

function qualifiedStruct(def: StructDef): string {
  return `fr::${def.scope === 'protocol' ? 'proto' : 'cap'}::${structCpp(def)}`;
}

/** decode_directory_entry, decode_display_ui_layout */
function structDecode(def: StructDef): string {
  return `decode_${snakeOf(structCpp(def))}`;
}

function elementCpp(el: ElementType): string {
  if (el.kind === 'scalar') {
    return SCALAR_CPP[el.name];
  }
  return el.kind === 'enum' ? enumCpp(el.def) : structCpp(el.def);
}

function typeCpp(t: TypeRef): string {
  switch (t.kind) {
    case 'scalar':
      return SCALAR_CPP[t.name];
    case 'enum':
      return enumCpp(t.def);
    case 'string':
      return 'std::string_view';
    case 'bytes':
      return 'std::span<const uint8_t>';
    case 'array':
      return `fr::proto::Array<${elementCpp(t.element)}, ${t.max}>`;
    case 'struct':
      return structCpp(t.def);
  }
}

/** typeCpp() usable outside fr::proto / fr::cap (host test tables). */
function qualifiedCpp(t: TypeRef): string {
  const el = (e: ElementType): string => (e.kind === 'scalar' ? SCALAR_CPP[e.name] : e.kind === 'enum' ? qualifiedEnum(e.def) : qualifiedStruct(e.def));
  if (t.kind === 'enum') {
    return qualifiedEnum(t.def);
  }
  if (t.kind === 'struct') {
    return qualifiedStruct(t.def);
  }
  return t.kind === 'array' ? `fr::proto::Array<${el(t.element)}, ${t.max}>` : typeCpp(t);
}

function qualifiedEnum(def: EnumDef): string {
  return `fr::${def.scope === 'protocol' ? 'proto' : 'cap'}::${enumCpp(def)}`;
}

/** Parameter type: arrays and messages by const reference, everything else (scalars, views) by value. */
function paramCpp(t: TypeRef): string {
  return t.kind === 'array' || t.kind === 'struct' ? `const ${typeCpp(t)} &` : `${typeCpp(t)} `;
}

const UNSIGNED: ReadonlySet<ScalarName> = new Set(['u8', 'u16', 'u32', 'u64', 'rgb', 'duration_ms']);

function intLit(v: bigint, name: ScalarName): string {
  if (name === 'rgb') {
    return hex(Number(v), 6);
  }
  if (name === 'u64') {
    return `${v}ull`;
  }
  if (name === 'i32' && v === -0x80000000n) {
    return '(-2147483647 - 1)';
  }
  return UNSIGNED.has(name) && v > 0x7fffffffn ? `${v}u` : `${v}`;
}

function f32Lit(v: number): string {
  if (Number.isNaN(v)) {
    return 'std::numeric_limits<float>::quiet_NaN()';
  }
  if (!Number.isFinite(v)) {
    return v > 0 ? 'std::numeric_limits<float>::infinity()' : '-std::numeric_limits<float>::infinity()';
  }
  const s = String(v);
  return /[.e]/.test(s) ? `${s}f` : `${s}.0f`;
}

/** A C++ string literal; octal escapes, since a hex escape would swallow following hex digits. */
function cString(s: string): string {
  let out = '"';
  for (const b of new TextEncoder().encode(s)) {
    if (b === 0x22) {
      out += '\\"';
    } else if (b === 0x5c) {
      out += '\\\\';
    } else if (b === 0x0a) {
      out += '\\n';
    } else if (b === 0x09) {
      out += '\\t';
    } else if (b < 0x20 || b >= 0x7f) {
      out += `\\${b.toString(8).padStart(3, '0')}`;
    } else {
      out += String.fromCharCode(b);
    }
  }
  return `${out}"`;
}

function enumMemberLit(def: EnumDef, v: unknown): string {
  if (typeof v === 'string') {
    const m = def.members.find((x) => x.name === v);
    if (!m) {
      throw new Error(`${def.name} has no member '${v}'`);
    }
    return `${enumCpp(def)}::${cppIdent(m.name)}`;
  }
  if (typeof v === 'number' && Number.isInteger(v)) {
    const m = def.members.find((x) => x.value === v);
    return m ? `${enumCpp(def)}::${cppIdent(m.name)}` : `static_cast<${enumCpp(def)}>(${v})`;
  }
  throw new Error(`expected a ${def.name} member name, got ${JSON.stringify(v)}`);
}

function scalarLit(name: ScalarName, v: unknown): string {
  if (name === 'bool') {
    if (typeof v !== 'boolean') {
      throw new Error(`expected a boolean, got ${JSON.stringify(v)}`);
    }
    return v ? 'true' : 'false';
  }
  if (name === 'f32') {
    if (typeof v !== 'number') {
      throw new Error(`expected a number, got ${JSON.stringify(v)}`);
    }
    return f32Lit(v);
  }
  let n: bigint;
  if (typeof v === 'number' && Number.isInteger(v)) {
    n = BigInt(v);
  } else if (typeof v === 'string' && /^-?\d+$/.test(v)) {
    n = BigInt(v);
  } else {
    throw new Error(`expected an integer, got ${JSON.stringify(v)}`);
  }
  const b = scalarBounds(name)!;
  if (n < b.min || n > b.max) {
    throw new Error(`${n} is outside the ${name} range`);
  }
  return intLit(n, name);
}

/** Initializer of a struct member: the YAML default, else the zero value; null means `{}`. */
function memberInit(t: TypeRef, def: JsonScalar | undefined): string | null {
  if (def !== undefined) {
    switch (t.kind) {
      case 'scalar':
        return scalarLit(t.name, def);
      case 'enum':
        return enumMemberLit(t.def, def);
      case 'string':
        return cString(String(def));
      default:
        throw new Error(`${t.kind} fields cannot have a default`);
    }
  }
  if (t.kind === 'scalar') {
    return t.name === 'bool' ? 'false' : t.name === 'f32' ? '0.0f' : '0';
  }
  if (t.kind === 'enum') {
    const zero = t.def.members.find((m) => m.value === 0);
    return zero ? `${enumCpp(t.def)}::${cppIdent(zero.name)}` : null;
  }
  return null;
}

function declare(t: TypeRef, name: string, def: JsonScalar | undefined): string {
  const init = memberInit(t, def);
  return init === null ? `${typeCpp(t)} ${name}{};` : `${typeCpp(t)} ${name} = ${init};`;
}

function fieldNote(f: { unit?: string; range?: [number, number]; doc?: string }): string {
  const parts: string[] = [];
  if (f.unit) {
    parts.push(f.unit);
  }
  if (f.range) {
    parts.push(`${f.range[0]}..${f.range[1]}`);
  }
  if (f.doc) {
    parts.push(oneLine(f.doc));
  }
  return parts.length > 0 ? `  // ${parts.join(', ')}` : '';
}

// ---- worst-case sizes for C++ buffers ----
// Unlike the model's budget sizes these ignore `range` and use the enum's underlying type: a decoded
// value may be anything the field's type holds, and re-encoding it must still fit kMaxSize.

function elementWireMax(el: ElementType): number {
  if (el.kind === 'enum') {
    return varintSize(UINT_MAX_VAL[el.def.underlying]);
  }
  if (el.kind === 'struct') {
    return structWireMax(el.def.fields);
  }
  if (el.name === 'f32') {
    return 4;
  }
  if (el.name === 'bool') {
    return 1;
  }
  const b = scalarBounds(el.name)!;
  // zigzag of the most negative value is the largest encoding of a signed type
  return varintSize(el.name.startsWith('i') ? -b.min * 2n - 1n : b.max);
}

function fieldWireMax(f: { id: number; type: TypeRef }): number {
  const t = f.type;
  const tag = tagSize(f.id);
  switch (t.kind) {
    case 'scalar':
      return tag + elementWireMax({ kind: 'scalar', name: t.name });
    case 'enum':
      return tag + elementWireMax(t);
    case 'string':
    case 'bytes':
      return tag + varintSize(t.max) + t.max;
    case 'array': {
      const el = elementWireMax(t.element);
      if (t.element.kind === 'struct') {
        return t.max * (tag + varintSize(el) + el);
      }
      return tag + varintSize(t.max * el) + t.max * el;
    }
    case 'struct': {
      const body = structWireMax(t.def.fields);
      return tag + varintSize(body) + body;
    }
  }
}

function structWireMax(fields: readonly { id: number; type: TypeRef }[]): number {
  return fields.reduce((n, f) => n + fieldWireMax(f), 0);
}

// ---- field codecs ----

function hasViews(fields: readonly Field[]): boolean {
  return fields.some((f) => f.type.kind === 'string' || f.type.kind === 'bytes');
}

function nonZero(t: TypeRef, x: string): string {
  switch (t.kind) {
    case 'scalar':
      if (t.name === 'bool') {
        return x;
      }
      // Bitwise for f32: -0.0 has non-zero bits and is written, as in the TS encoder (`!Object.is(v, 0)`),
      // so it round-trips (fr::proto::same compares bits).
      return t.name === 'f32' ? `std::bit_cast<uint32_t>(${x}) != 0u` : `${x} != 0`;
    case 'enum':
      return `${x} != ${enumCpp(t.def)}{}`;
    default:
      return `!${x}.empty()`;
  }
}

function writeElement(el: ElementType, e: string): string {
  if (el.kind === 'enum') {
    return `w.varint(std::to_underlying(${e}));`;
  }
  if (el.kind === 'struct') {
    throw new Error('struct elements are written per field');
  }
  if (el.name === 'bool') {
    return `w.varint(${e} ? 1 : 0);`;
  }
  if (el.name === 'f32') {
    return `w.f32(${e});`;
  }
  return el.name.startsWith('i') ? `w.sint(${e});` : `w.varint(${e});`;
}

function writeValue(c: Code, f: Field, x: string): void {
  const t = f.type;
  switch (t.kind) {
    case 'scalar':
      if (t.name === 'bool') {
        c.line(`w.field_bool(${f.id}, ${x});`);
      } else if (t.name === 'f32') {
        c.line(`w.field_f32(${f.id}, ${x});`);
      } else if (t.name.startsWith('i')) {
        c.line(`w.field_sint(${f.id}, ${x});`);
      } else {
        c.line(`w.field_uint(${f.id}, ${x});`);
      }
      return;
    case 'enum':
      c.line(`w.field_uint(${f.id}, std::to_underlying(${x}));`);
      return;
    case 'string':
      c.line(`w.field_string(${f.id}, ${x});`);
      return;
    case 'bytes':
      c.line(`w.field_bytes(${f.id}, ${x});`);
      return;
    case 'struct':
      c.line(`const auto m = w.begin_len(${f.id});`).line(`encode(${x}, w);`).line('w.end_len(m);');
      return;
    case 'array':
      if (t.element.kind === 'struct') {
        c.open(`for (const auto &e : ${x})`, () => {
          c.line(`const auto m = w.begin_len(${f.id});`).line('encode(e, w);').line('w.end_len(m);');
        });
      } else {
        const el = t.element;
        c.line(`const auto m = w.begin_len(${f.id});`);
        c.open(`for (const auto e : ${x})`, () => c.line(writeElement(el, 'e')));
        c.line('w.end_len(m);');
      }
      return;
  }
}

/** Writes one field of `x` (the value expression), honouring its presence. */
function encodeField(c: Code, f: Field, x: string, has: string | null): void {
  if (f.presence === 'optional' && has !== null) {
    c.open(`if (${has})`, () => writeValue(c, f, x));
  } else if (f.presence === 'always') {
    if (f.type.kind === 'array' || f.type.kind === 'struct') {
      c.block(() => writeValue(c, f, x));
    } else {
      writeValue(c, f, x);
    }
  } else if (f.type.kind === 'array' && f.type.element.kind === 'struct') {
    writeValue(c, f, x);  // one field per element: an empty array writes nothing anyway
  } else {
    c.open(`if (${nonZero(f.type, x)})`, () => writeValue(c, f, x));
  }
}

/** An unsigned bound: the type's maximum as hex, anything else in decimal. */
function uintLit(v: bigint): string {
  if (v === 0xffn || v === 0xffffn || v === 0xffffffffn) {
    return `0x${v.toString(16).toUpperCase()}`;
  }
  return v > 0x7fffffffn ? `${v}u` : `${v}`;
}

function sintLit(v: bigint): string {
  const named: Record<string, string> = { '-128': '-0x80', '127': '0x7F', '-32768': '-0x8000', '32767': '0x7FFF', '-2147483648': 'INT32_MIN', '2147483647': 'INT32_MAX' };
  return named[String(v)] ?? `${v}`;
}

/** A known field's value from reader `r`, checked against its type (not its range). */
function readField(t: TypeRef, r: string): string {
  switch (t.kind) {
    case 'scalar': {
      const name = t.name;
      if (name === 'bool') {
        return `${r}.read_bool()`;
      }
      if (name === 'f32') {
        return `${r}.read_f32()`;
      }
      if (name === 'u64') {
        return `${r}.read_uint64()`;
      }
      const b = scalarBounds(name)!;
      const cpp = SCALAR_CPP[name];
      if (name.startsWith('i')) {
        const read = `${r}.read_sint(${sintLit(b.min)}, ${sintLit(b.max)})`;
        return name === 'i32' ? read : `static_cast<${cpp}>(${read})`;
      }
      return `static_cast<${cpp}>(${r}.read_uint(${uintLit(b.max)}))`;
    }
    case 'enum':
      // Open: any value of the underlying type decodes; valid() tells members apart.
      return `static_cast<${enumCpp(t.def)}>(${r}.read_uint(${uintLit(BigInt(UINT_MAX_VAL[t.def.underlying]))}))`;
    case 'string':
      return `${r}.read_string(${t.max})`;
    case 'bytes':
      return `${r}.read_bytes(${t.max})`;
    case 'array':
      throw new Error('arrays are decoded element by element');
    case 'struct':
      throw new Error('messages are decoded from their bytes');
  }
}

/** One packed element (no tag); arrays carry no range. */
function readElement(el: ElementType, r: string): string {
  if (el.kind === 'enum') {
    return `static_cast<${enumCpp(el.def)}>(${r}.raw_uint(${uintLit(BigInt(UINT_MAX_VAL[el.def.underlying]))}))`;
  }
  if (el.kind === 'struct') {
    throw new Error('struct elements are repeated, not packed');
  }
  switch (el.name) {
    case 'bool':
      return `${r}.raw_uint(1) == 1`;
    case 'f32':
      return `${r}.raw_f32()`;
    case 'u64':
      return `${r}.raw_uint(UINT64_MAX)`;
    case 'i32':
      return `${r}.raw_sint(INT32_MIN, INT32_MAX)`;
    default: {
      const b = scalarBounds(el.name)!;
      const raw = el.name.startsWith('i') ? `${r}.raw_sint(${sintLit(b.min)}, ${sintLit(b.max)})` : `${r}.raw_uint(${uintLit(b.max)})`;
      return `static_cast<${SCALAR_CPP[el.name]}>(${raw})`;
    }
  }
}

/** `case <id>:` of a decoder's switch; `x` is the target lvalue, `has` its has_ flag. */
function decodeCase(c: Code, f: Field, x: string, has: string | null): void {
  const t = f.type;
  const setHas = () => {
    if (f.presence === 'optional' && has !== null) {
      c.line(`${has} = true;`);
    }
  };
  if (t.kind === 'struct') {
    // One nested message; the last occurrence wins, as for scalars.
    c.line(`case ${f.id}: {`).indent();
    c.line('const auto b = r.read_bytes(SIZE_MAX);');
    c.open('if (!r.ok())', () => c.line('break;'));
    c.line(`const auto e = ${structDecode(t.def)}(b);`);
    c.line('if (e) {').indent().line(`${x} = *e;`).dedent();
    c.line('} else {').indent().line('r.fail(e.error());').dedent().line('}');
    c.line('break;').dedent().line('}');
    return;
  }
  if (t.kind !== 'array') {
    c.line(`case ${f.id}:`).indent();
    setHas();
    c.line(`${x} = ${readField(t, 'r')};`).line('break;').dedent();
    return;
  }
  c.line(`case ${f.id}: {`).indent();
  setHas();
  const el = t.element;
  if (el.kind === 'struct') {
    // One occurrence per element; occurrence max+1 is too_long before it is read.
    c.open(`if (${x}.full())`, () => c.line('r.fail(fr::wire::DecodeErr::too_long);').line('break;'));
    c.line('const auto b = r.read_bytes(SIZE_MAX);');
    c.open('if (!r.ok())', () => c.line('break;'));
    c.line(`const auto e = ${structDecode(el.def)}(b);`);
    c.line('if (e) {').indent().line(`${x}.push_back(*e);`).dedent();
    c.line('} else {').indent().line('r.fail(e.error());').dedent().line('}');
  } else {
    c.line('auto sub = r.read_sub();');
    c.line(`${x}.clear();`);
    c.open('while (!sub.at_end())', () => {
      c.open(`if (${x}.full())`, () => c.line('sub.fail(fr::wire::DecodeErr::too_long);').line('break;'));
      c.line(`const auto e = ${readElement(el, 'sub')};`);
      c.open('if (sub.ok())', () => c.line(`${x}.push_back(e);`));
    });
    c.line('r.adopt(sub);');
  }
  c.line('break;').dedent().line('}');
}

/** 'DirectoryEntry' -> 'directory_entry' */
function snakeOf(pascal: string): string {
  return pascal.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
}

function sameExpr(t: TypeRef, a: string, b: string): string {
  if (t.kind === 'bytes') {
    return `fr::proto::equal_bytes(${a}, ${b})`;
  }
  if (t.kind === 'scalar' && t.name === 'f32') {
    return `fr::proto::same(${a}, ${b})`;
  }
  return `${a} == ${b}`;
}

/**
 * The schema checks of one field (TS `invalid()`): an enum value must be a member, a number inside its
 * range (so never a NaN) unless it is an implicit zero, which is the absent field (design c2 §3; an f32
 * -0.0 counts as zero, as `v === 0` does in TS); absent optional fields are skipped.
 */
function validClauses(f: Field, x: string): string[] {
  const out: string[] = [];
  const t = f.type;
  if (t.kind === 'enum') {
    out.push(`is_known(${x})`);
  } else if (t.kind === 'array' && t.element.kind === 'enum') {
    out.push(`std::ranges::all_of(${x}, [](${enumCpp(t.element.def)} e) { return is_known(e); })`);
  } else if (t.kind === 'struct' && t.def.scope !== 'protocol') {
    // Capability message types have valid() (protocol types are not checked against the schema).
    out.push(`valid(${x})`);
  } else if (t.kind === 'array' && t.element.kind === 'struct' && t.element.def.scope !== 'protocol') {
    out.push(`std::ranges::all_of(${x}, [](const ${structCpp(t.element.def)} &e) { return valid(e); })`);
  } else if (t.kind === 'scalar' && f.range) {
    const [lo, hi] = f.range;
    const parts: string[] = [];
    if (t.name === 'f32') {
      parts.push(`${x} >= ${f32Lit(lo)}`, `${x} <= ${f32Lit(hi)}`);
    } else {
      const b = scalarBounds(t.name)!;
      // Bounds the type already guarantees would be tautological comparisons (-Wtype-limits).
      if (BigInt(lo) > b.min) {
        parts.push(`${x} >= ${intLit(BigInt(lo), t.name)}`);
      }
      if (BigInt(hi) < b.max) {
        parts.push(`${x} <= ${intLit(BigInt(hi), t.name)}`);
      }
    }
    if (parts.length > 0) {
      out.push(zeroExempt(f) ? `(${x} == 0 || (${parts.join(' && ')}))` : parts.join(' && '));
    }
  }
  if (out.length > 0 && f.presence === 'optional') {
    return [`(!v.has_${f.name} || (${out.join(' && ')}))`];
  }
  return out;
}

// ---- structs ----

interface StructSpec {
  /** C++ struct name. */
  name: string;
  fields: Field[];
  /** decode_<snake> */
  decode: string;
  comment: string[];
  /** Extra `static constexpr` lines (message class and kind). */
  statics: string[];
  /** Generate `bool valid(const T&)` (capability structs). */
  validate: boolean;
}

function emitStructDecl(c: Code, s: StructSpec): void {
  c.lines(s.comment);
  c.open(`struct ${s.name}`, () => {
    for (const f of s.fields) {
      if (f.presence === 'optional') {
        c.line(`bool has_${f.name} = false;`);
      }
      c.line(`${declare(f.type, cppIdent(f.name), f.default)}${fieldNote(f)}`);
    }
    if (s.fields.length > 0) {
      c.line();
    }
    c.lines(s.statics);
    c.line(`static constexpr size_t kMaxSize = ${structWireMax(s.fields)};`);
  }, '};');
  c.line(`size_t encode(const ${s.name} &v, fr::wire::Writer &w);`);
  c.line(`std::expected<${s.name}, fr::wire::DecodeErr> ${s.decode}(std::span<const uint8_t> in);`);
  c.line(`bool operator==(const ${s.name} &a, const ${s.name} &b);`);
  if (s.validate) {
    c.line(`bool valid(const ${s.name} &v);`);
  }
  c.line();
}

function emitStructDefs(c: Code, s: StructSpec): void {
  const empty = s.fields.length === 0;
  c.fn(`size_t encode(const ${s.name} &${empty ? '' : 'v'}, fr::wire::Writer &${empty ? '' : 'w'})`, () => {
    if (empty) {
      c.line('return 0;');
      return;
    }
    c.line('const size_t start = w.size();');
    for (const f of s.fields) {
      encodeField(c, f, `v.${cppIdent(f.name)}`, `v.has_${f.name}`);
    }
    c.line('return w.size() - start;');
  });
  c.line();
  c.fn(`std::expected<${s.name}, fr::wire::DecodeErr> ${s.decode}(std::span<const uint8_t> in)`, () => {
    c.line(`${s.name} v{};`);
    c.line('fr::wire::Reader r(in);');
    emitDecodeLoop(c, s.fields.map((f) => ({ f, x: `v.${cppIdent(f.name)}`, has: `v.has_${f.name}` })));
    c.open('if (!r.ok())', () => c.line('return std::unexpected(r.error());'));
    c.line('return v;');
  });
  c.line();
  c.fn(`bool operator==(const ${s.name} &${empty ? '' : 'a'}, const ${s.name} &${empty ? '' : 'b'})`, () => {
    if (empty) {
      c.line('return true;');
      return;
    }
    const clauses: string[] = [];
    for (const f of s.fields) {
      const n = cppIdent(f.name);
      const eq = sameExpr(f.type, `a.${n}`, `b.${n}`);
      clauses.push(f.presence === 'optional' ? `a.has_${f.name} == b.has_${f.name} && (!a.has_${f.name} || ${eq})` : eq);
    }
    emitReturnAll(c, clauses);
  });
  c.line();
  if (s.validate) {
    const clauses = s.fields.flatMap((f) => validClauses(f, `v.${cppIdent(f.name)}`));
    c.fn(`bool valid(const ${s.name} &${clauses.length > 0 ? 'v' : ''})`, () => emitReturnAll(c, clauses));
    c.line();
  }
}

function emitDecodeLoop(c: Code, targets: { f: Field; x: string; has: string | null }[]): void {
  c.open('while (r.next())', () => {
    if (targets.length === 0) {
      c.line('r.skip();');
      return;
    }
    c.open('switch (r.field())', () => {
      c.dedent();
      for (const { f, x, has } of targets) {
        decodeCase(c, f, x, has);
      }
      c.line('default:').indent().line('r.skip();').line('break;').dedent();
      c.indent();
    });
  });
}

/** Drops parentheses around a whole expression (a lone `(a || b)` clause needs none). */
function unwrap(expr: string): string {
  if (!expr.startsWith('(') || !expr.endsWith(')')) {
    return expr;
  }
  let depth = 0;
  for (let i = 0; i < expr.length; i++) {
    depth += expr[i] === '(' ? 1 : expr[i] === ')' ? -1 : 0;
    if (depth === 0 && i < expr.length - 1) {
      return expr;  // the first parenthesis closes before the end: `(a) || (b)`
    }
  }
  return expr.slice(1, -1);
}

/** `return a && b && ...;`, one clause per line when it does not fit. */
function emitReturnAll(c: Code, clauses: string[]): void {
  if (clauses.length === 0) {
    c.line('return true;');
    return;
  }
  if (clauses.length === 1) {
    clauses = [unwrap(clauses[0])];
  }
  const single = `return ${clauses.join(' && ')};`;
  if (single.length <= 100) {
    c.line(single);
    return;
  }
  c.line(`return ${clauses[0]} &&`);
  clauses.slice(1).forEach((cl, i) => c.line(`       ${cl}${i === clauses.length - 2 ? ';' : ' &&'}`));
}

// ---- enums ----

function emitEnumDecl(c: Code, def: EnumDef): void {
  const name = enumCpp(def);
  const members = def.members.map((m) => `${cppIdent(m.name)} = ${m.value}`);
  const single = `enum class ${name} : ${UNDERLYING_CPP[def.underlying]} { ${members.join(', ')} };`;
  if (single.length <= 110) {
    c.line(single);
  } else {
    c.open(`enum class ${name} : ${UNDERLYING_CPP[def.underlying]}`, () => members.forEach((m) => c.line(`${m},`)), '};');
  }
  c.line(`/** The YAML member name; nullptr for a value this build does not know. */`);
  c.line(`const char *to_name(${name} v);`);
  c.line(`bool from_name(std::string_view s, ${name} &out);`);
  c.fn(`constexpr bool is_known(${name} v)`, () => {
    c.open('switch (v)', () => {
      c.dedent();
      for (const m of def.members) {
        c.line(`case ${name}::${cppIdent(m.name)}:`);
      }
      c.indent().line('return true;').dedent();
      c.indent();
    });
    c.line('return false;');
  });
  c.line();
}

function emitEnumDefs(c: Code, def: EnumDef): void {
  const name = enumCpp(def);
  c.fn(`const char *to_name(${name} v)`, () => {
    c.open('switch (v)', () => {
      c.dedent();
      for (const m of def.members) {
        c.line(`case ${name}::${cppIdent(m.name)}:`).indent().line(`return ${cString(m.name)};`).dedent();
      }
      c.indent();
    });
    c.line('return nullptr;');
  });
  c.line();
  c.fn(`bool from_name(std::string_view s, ${name} &out)`, () => {
    for (const m of def.members) {
      c.open(`if (s == ${cString(m.name)})`, () => c.line(`out = ${name}::${cppIdent(m.name)};`).line('return true;'));
    }
    c.line('return false;');
  });
  c.line();
}

