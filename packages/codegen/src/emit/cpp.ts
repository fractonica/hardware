function hexBytes(h: string): number[] {
  const clean = h.replace(/\s+/g, '');
  if (!/^([0-9a-fA-F]{2})*$/.test(clean)) {
    throw new Error(`not a hex string: ${JSON.stringify(h)}`);
  }
  const out: number[] = [];
  for (let i = 0; i < clean.length; i += 2) {
    out.push(parseInt(clean.slice(i, i + 2), 16));
  }
  return out;
}

function bytesInit(b: readonly number[]): string {
  return `{${b.map((x) => `0x${x.toString(16).padStart(2, '0')}`).join(', ')}}`;
}

function hexOf(b: Uint8Array | readonly number[]): string {
  return [...b].map((x) => x.toString(16).padStart(2, '0')).join('');
}

/** Emits statements that build a C++ value of struct `fields` from a vector's JSON value. */
class VectorWriter {
  private readonly c: Code;
  private pool = 0;
  private depth = 0;

  constructor(c: Code) {
    this.c = c;
  }

  staticBytes(b: readonly number[]): string {
    if (b.length === 0) {
      return 'std::span<const uint8_t>{}';
    }
    const name = `b${this.pool++}`;
    this.c.line(`static constexpr uint8_t ${name}[] = ${bytesInit(b)};`);
    return `std::span<const uint8_t>(${name})`;
  }

  valueExpr(t: TypeRef, v: unknown, where: string): string {
    try {
      switch (t.kind) {
        case 'scalar':
          return scalarLit(t.name, v);
        case 'enum':
          return enumMemberLit(t.def, v);
        case 'string': {
          if (typeof v !== 'string') {
            throw new Error(`expected a string, got ${JSON.stringify(v)}`);
          }
          return `std::string_view(${cString(v)}, ${new TextEncoder().encode(v).length})`;
        }
        case 'bytes':
          if (typeof v !== 'string') {
            throw new Error(`expected a hex string, got ${JSON.stringify(v)}`);
          }
          return this.staticBytes(hexBytes(v));
        case 'array': {
          if (!Array.isArray(v)) {
            throw new Error(`expected an array, got ${JSON.stringify(v)}`);
          }
          const el = t.element;
          if (el.kind === 'struct') {
            throw new Error('struct arrays are assigned element by element');
          }
          const elType: TypeRef = el.kind === 'scalar' ? { kind: 'scalar', name: el.name } : el;
          return `${typeCpp(t)}{${v.map((x, i) => this.valueExpr(elType, x, `${where}[${i}]`)).join(', ')}}`;
        }
        case 'struct':
          throw new Error('messages are assigned field by field');
      }
    } catch (e) {
      throw new Error(`${where}: ${(e as Error).message}`);
    }
  }

  /** `target.field = ...;` for each key of `value`. */
  assign(fields: readonly Field[], value: unknown, target: string, where: string): void {
    if (value === null || typeof value !== 'object' || Array.isArray(value)) {
      throw new Error(`${where}: expected an object, got ${JSON.stringify(value)}`);
    }
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      const f = fields.find((x) => x.name === k);
      if (!f) {
        throw new Error(`${where}: unknown field '${k}'`);
      }
      if (f.presence === 'optional') {
        this.c.line(`${target}.has_${f.name} = true;`);
      }
      const x = `${target}.${cppIdent(f.name)}`;
      if (f.type.kind === 'struct') {
        this.assign(f.type.def.fields, v, x, `${where}.${k}`);
        continue;
      }
      if (f.type.kind === 'array' && f.type.element.kind === 'struct') {
        if (!Array.isArray(v)) {
          throw new Error(`${where}.${k}: expected an array`);
        }
        const def = f.type.element.def;
        // One name per nesting level: an element of an element must not shadow its parent.
        const e = `e${this.depth}`;
        this.depth++;
        v.forEach((el, i) => {
          this.c.block(() => {
            this.c.line(`${qualifiedStruct(def)} ${e}{};`);
            this.assign(def.fields, el, e, `${where}.${k}[${i}]`);
            this.c.line(`${x}.push_back(${e});`);
          });
        });
        this.depth--;
        continue;
      }
      this.c.line(`${x} = ${this.valueExpr(f.type, v, `${where}.${k}`)};`);
    }
  }
}

const HEADER_KEYS = ['flags', 'cls', 'kind', 'seq', 'net', 'src', 'dst', 'epoch', 'ttl', 'port'] as const;

function emitHeaderValue(c: Code, vw: VectorWriter, h: Header, target: string): void {
  c.line(`fr::wire::Header ${target}{};`);
  for (const k of HEADER_KEYS) {
    if (h[k] !== 0) {
      const bits = k === 'flags' || k === 'ttl';
      c.line(`${target}.${k} = ${bits ? hex(h[k], 2) : h[k] > 0xff ? hex(h[k], 4) : h[k]};`);
    }
  }
  const tlvs = extBytes(h);
  if (tlvs.length > 0) {
    c.line(`${target}.ext = fr::wire::ExtView(${vw.staticBytes(tlvs)});`);
  }
}

/** The TLV block of a decoded header, as on the wire after its `len` byte. */
function extBytes(h: Header): number[] {
  return (h.ext ?? []).flatMap((t) => [t.type, t.value.length, ...t.value]);
}

function headerFromValue(v: unknown, bytes: number[], where: string): Header {
  const decoded = unpackHeader(Uint8Array.from(bytes));
  if (!decoded.ok) {
    throw new Error(`${where}: header bytes do not decode (${decoded.error})`);
  }
  // The golden bytes are the truth; a value that disagrees with them is a broken vector.
  if (v !== null && typeof v === 'object') {
    for (const k of HEADER_KEYS) {
      const x = (v as Record<string, unknown>)[k];
      if (x !== undefined && x !== decoded.value[k]) {
        throw new Error(`${where}: header.${k} is ${JSON.stringify(x)} but the bytes say ${decoded.value[k]}`);
      }
    }
    const ext = (v as Record<string, unknown>).ext;
    if (ext !== undefined) {
      const want = hexOf((ext as { type: number; value: string }[]).flatMap((t) => [t.type, t.value.length / 2, ...hexBytes(t.value)]));
      if (want !== hexOf(extBytes(decoded.value))) {
        throw new Error(`${where}: header.ext disagrees with the bytes`);
      }
    }
  }
  return decoded.value;
}

