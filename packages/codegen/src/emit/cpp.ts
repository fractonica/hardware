const LAYOUT_CPP = { u8: 'uint8_t', i8: 'int8_t', u16: 'uint16_t', u32: 'uint32_t', mac: 'std::array<uint8_t, 6>' } as const;

/** 'GW_TX_DONE' -> 'GwTxDone' */
function serialStructName(b: SerialBody): string {
  return b.kind === 'message' ? b.message!.name : pascalUpper(b.name);
}

function serialDecodeName(b: SerialBody): string {
  return `decode_${snakeOf(serialStructName(b))}`;
}

function layoutCpp(f: SerialLayoutField): string {
  return f.type === 'enum' ? enumCpp(f.enum!) : LAYOUT_CPP[f.type];
}

function layoutWire(b: SerialBody): string {
  const parts = b.layout.map((f) => (f.type === 'mac' ? `${f.name}[6]` : `${f.name} ${f.type === 'enum' ? f.enum!.name : f.type}`));
  return [...parts, ...(b.envelope ? ['envelope'] : [])].join(' | ');
}

function serialHeader(model: Model): string {
  const p = model.protocol;
  const c = new Code();
  c.line(`${GENERATED} Source: ${p.file}`);
  c.line('// Serial frame bodies (spec 05 §5.12.3, design m2-c4-gateway D1): fixed little-endian layouts, GW_RX and GW_TX');
  c.line('// with the envelope after theirs, and the protobuf-wire GW_STATUS, GW_CMD and GW_RSP (their structs and codecs');
  c.line('// are in messages.hpp). A decoded envelope (`env`) is a view into the body and the decoders copy nothing;');
  c.line('// encode_line writes a whole `@fr1:` line from a struct, streaming `env` from where it lies.');
  c.line('#pragma once').line();
  c.lines(['#include <array>', '#include <cstddef>', '#include <cstdint>', '#include <expected>', '#include <span>']).line();
  c.lines(['#include "fr/serial_line.hpp"', '#include "fr/wire.hpp"', '#include "messages.hpp"', '#include "protocol.hpp"']).line();
  c.line('namespace fr::proto {').line();
  for (const b of p.serial.bodies) {
    const k = `fr::wire::kSerial${pascalUpper(b.name)}`;
    if (b.kind === 'message') {
      const n = b.message!.name;
      c.line(`// ${b.name} (${hex(b.code, 2)}): ${n}, protobuf-wire; decode_${snakeOf(n)}() decodes the body.`);
      c.line(`inline constexpr uint8_t kSerialTypeOf${n} = ${k};`);
      c.line(`/** One \`@fr1:\` line without the terminator; 0 if \`out\` is too small. */`);
      c.line(`size_t encode_line(const ${n} &v, std::span<char> out);`);
      c.line();
      continue;
    }
    const n = serialStructName(b);
    c.line(`// ${b.name} (${hex(b.code, 2)}): ${layoutWire(b)}`);
    c.open(`struct ${n}`, () => {
      for (const f of b.layout) {
        const init = f.type === 'mac' ? '{}' : f.type === 'enum' ? (f.enum!.members.some((m) => m.value === 0) ? ` = ${enumCpp(f.enum!)}::${cppIdent(f.enum!.members.find((m) => m.value === 0)!.name)}` : '{}') : ' = 0';
        c.line(`${layoutCpp(f)} ${cppIdent(f.name)}${init};${f.doc ? `  // ${oneLine(f.doc)}` : ''}`);
      }
      if (b.envelope) {
        c.line('std::span<const uint8_t> env{};  // the envelope bytes (not decoded); decoded, a view into the body');
      }
      c.line();
      c.line(`static constexpr uint8_t kType = ${k};`);
      c.line(`static constexpr size_t kPrefixSize = ${b.prefixSize};`);
      c.line(`static constexpr bool kEnvelope = ${b.envelope};`);
      c.line(`static constexpr size_t kMaxSize = ${b.envelope ? 'fr::wire::kMaxLineBody' : 'kPrefixSize'};`);
    }, '};');
    c.line(b.envelope ? '/** The prefix, then `env`. */' : '/** The kPrefixSize bytes. */');
    c.line(`size_t encode(const ${n} &v, fr::wire::Writer &w);`);
    c.line(
      b.envelope
        ? `/** Shorter than kPrefixSize is truncated; \`env\` is the rest of \`in\`. */`
        : '/** Exactly kPrefixSize bytes: shorter is truncated, longer too_long. */',
    );
    c.line(`std::expected<${n}, fr::wire::DecodeErr> ${serialDecodeName(b)}(std::span<const uint8_t> in);`);
    c.line(
      b.envelope
        ? '/** One `@fr1:` line without the terminator, `env` streamed, not copied; 0 if over kMaxLine or `out` is too small. */'
        : '/** One `@fr1:` line without the terminator; 0 if `out` is too small. */',
    );
    c.line(`size_t encode_line(const ${n} &v, std::span<char> out);`);
    c.line(`bool operator==(const ${n} &a, const ${n} &b);`);
    c.line();
  }
  c.trim().line().line('}  // namespace fr::proto');
  return c.text();
}

function serialSource(model: Model): string {
  const p = model.protocol;
  const c = new Code();
  c.line(`${GENERATED} Source: ${p.file}`);
  c.line('#include "serial.hpp"').line();
  c.line('#include <algorithm>').line();
  c.line('namespace fr::proto {');
  c.line('namespace {').line();
  c.fn('uint16_t le16(std::span<const uint8_t> b, size_t at)', () => c.line('return static_cast<uint16_t>(b[at] | (b[at + 1] << 8));'));
  c.line();
  c.fn('uint32_t le32(std::span<const uint8_t> b, size_t at)', () => c.line('return le16(b, at) | (static_cast<uint32_t>(le16(b, at + 2)) << 16);'));
  c.line();
  const layouts = p.serial.bodies.filter((b) => b.kind === 'layout');
  for (const b of layouts) {
    const n = serialStructName(b);
    c.fn(`void write_prefix(const ${n} &v, fr::wire::Writer &w)`, () => {
      for (const f of b.layout) {
        const x = `v.${cppIdent(f.name)}`;
        switch (f.type) {
          case 'mac':
            c.line(`w.raw(${x});`);
            break;
          case 'enum':
          case 'i8':
            c.line(`w.u8(static_cast<uint8_t>(${x}));`);
            break;
          case 'u8':
            c.line(`w.u8(${x});`);
            break;
          case 'u16':
            c.line(`w.u16le(${x});`);
            break;
          case 'u32':
            c.line(`w.u32le(${x});`);
            break;
        }
      }
    });
    c.line();
  }
  c.line('}  // namespace').line();
  for (const b of p.serial.bodies) {
    const n = serialStructName(b);
    if (b.kind === 'message') {
      c.fn(`size_t encode_line(const ${n} &v, std::span<char> out)`, () => {
        c.line(`uint8_t body[${n}::kMaxSize];`);
        c.line('fr::wire::Writer w(body, sizeof(body));');
        c.line('encode(v, w);');
        c.line(`return w.overflow() ? 0 : fr::wire::encode_line(kSerialTypeOf${n}, w.bytes(), out);`);
      });
      c.line();
      continue;
    }
    c.fn(`size_t encode(const ${n} &v, fr::wire::Writer &w)`, () => {
      c.line('const size_t start = w.size();');
      c.line('write_prefix(v, w);');
      if (b.envelope) {
        c.line('w.raw(v.env);');
      }
      c.line('return w.size() - start;');
    });
    c.line();
    c.fn(`std::expected<${n}, fr::wire::DecodeErr> ${serialDecodeName(b)}(std::span<const uint8_t> in)`, () => {
      if (b.envelope) {
        c.open(`if (in.size() < ${n}::kPrefixSize)`, () => c.line('return std::unexpected(fr::wire::DecodeErr::truncated);'));
      } else {
        c.open(`if (in.size() != ${n}::kPrefixSize)`, () =>
          c.line('using fr::wire::DecodeErr;').line(`return std::unexpected(in.size() < ${n}::kPrefixSize ? DecodeErr::truncated : DecodeErr::too_long);`),
        );
      }
      c.line(`${n} v{};`);
      for (const f of b.layout) {
        const x = `v.${cppIdent(f.name)}`;
        switch (f.type) {
          case 'mac':
            c.line(`std::copy_n(in.begin() + ${f.offset}, 6, ${x}.begin());`);
            break;
          case 'enum':
            c.line(`${x} = static_cast<${enumCpp(f.enum!)}>(in[${f.offset}]);`);
            break;
          case 'i8':
            c.line(`${x} = static_cast<int8_t>(in[${f.offset}]);`);
            break;
          case 'u8':
            c.line(`${x} = in[${f.offset}];`);
            break;
          case 'u16':
            c.line(`${x} = le16(in, ${f.offset});`);
            break;
          case 'u32':
            c.line(`${x} = le32(in, ${f.offset});`);
            break;
        }
      }
      if (b.envelope) {
        c.line(`v.env = in.subspan(${n}::kPrefixSize);`);
      }
      c.line('return v;');
    });
    c.line();
    c.fn(`size_t encode_line(const ${n} &v, std::span<char> out)`, () => {
      c.line(`uint8_t prefix[${n}::kPrefixSize];`);
      c.line('fr::wire::Writer w(prefix, sizeof(prefix));');
      c.line('write_prefix(v, w);');
      c.line(b.envelope ? `return fr::wire::encode_line(${n}::kType, w.bytes(), v.env, out);` : `return fr::wire::encode_line(${n}::kType, w.bytes(), out);`);
    });
    c.line();
    c.fn(`bool operator==(const ${n} &a, const ${n} &b)`, () => {
      const clauses = b.layout.map((f) => `a.${cppIdent(f.name)} == b.${cppIdent(f.name)}`);
      if (b.envelope) {
        clauses.push('equal_bytes(a.env, b.env)');
      }
      emitReturnAll(c, clauses);
    });
    c.line();
  }
  c.trim().line().line('}  // namespace fr::proto');
  return c.text();
}

// ---- fr_caps/gen: one capability ----

interface CapNames {
  traits: string;
  config: string;
  args: (cmd: Command) => string;
  result: (cmd: Command) => string;
  event: (ev: Event) => string;
}

function capNames(cap: Capability): CapNames {
  const P = cap.pascalName;
  return {
    traits: `${P}Traits`,
    config: `${P}Config`,
    args: (cmd) => `${P}${pascalCase(cmd.name)}Args`,
    result: (cmd) => `${P}${pascalCase(cmd.name)}Result`,
    event: (ev) => `${P}${pascalCase(ev.name)}`,
  };
}

/** The capability's message types (design m2-c5-display D2), in YAML order: each may hold the ones before it. */
function capTypeSpecs(cap: Capability): StructSpec[] {
  return cap.types.map((t) => ({
    name: structCpp(t),
    fields: t.fields,
    decode: structDecode(t),
    comment: docLines(`${cap.name} ${t.name} (message type)${t.doc ? `: ${oneLine(t.doc)}` : '.'}`),
    statics: [],
    validate: true,
  }));
}

function capStructs(cap: Capability): StructSpec[] {
  const n = capNames(cap);
  const s = cap.shortName;
  const out: StructSpec[] = [];
  if (cap.traits.length > 0) {
    out.push({ name: n.traits, fields: cap.traits, decode: `decode_${s}_traits`, comment: ['// Traits (descriptor bytes): derived from config and driver features, never set directly.'], statics: [], validate: true });
  }
  for (const cmd of cap.commands) {
    if (cmd.fields.length > 0) {
      out.push({ name: n.args(cmd), fields: cmd.fields, decode: `decode_${s}_${cmd.name}_args`, comment: [`// ${cap.name}.${cmd.name} arguments.`], statics: [], validate: true });
    }
    if (cmd.result) {
      out.push({ name: n.result(cmd), fields: cmd.result, decode: `decode_${s}_${cmd.name}_result`, comment: [`// ${cap.name}.${cmd.name} result.`], statics: [], validate: true });
    }
  }
  for (const ev of cap.events) {
    out.push({ name: n.event(ev), fields: ev.fields, decode: `decode_${s}_${ev.name}`, comment: [`// ${cap.name}.${ev.name} event (${ev.priority}).`], statics: [], validate: true });
  }
  return out;
}

/** Fails generation on C++ name clashes the schema validator cannot see (they depend on naming rules). */
function checkCapNames(cap: Capability): void {
  const seen = new Map<string, string>();
  const claim = (name: string, what: string) => {
    const other = seen.get(name);
    if (other) {
      throw new Error(`${cap.file}: generated C++ name ${name} (${what}) clashes with ${other}`);
    }
    seen.set(name, what);
  };
  for (const e of cap.enums) {
    claim(enumCpp(e), `enum ${e.name}`);
  }
  claim(cap.pascalName, 'the capability class');
  claim(`${cap.pascalName}Config`, 'config');
  for (const s of [...capTypeSpecs(cap), ...capStructs(cap)]) {
    claim(s.name, s.comment[0]);
    claim(s.decode, `${s.name} decoder`);
  }
  for (const p of cap.properties) {
    claim(`decode_${cap.shortName}_${p.name}_state`, `property ${p.name}`);
  }
}

function stateFns(cap: Capability, p: Property) {
  const base = `${cap.shortName}_${p.name}_state`;
  return { encode: `encode_${base}`, decode: `decode_${base}`, max: `k${cap.pascalName}${pascalCase(p.name)}StateMaxSize` };
}

function requiresExpr(cap: Capability, r: { trait: string; eq?: JsonScalar }, t: string): string {
  const trait = cap.traits.find((x) => x.name === r.trait)!;
  const x = `${t}.${cppIdent(trait.name)}`;
  if (r.eq === undefined) {
    return x;
  }
  if (trait.type.kind === 'enum') {
    return `${x} == ${enumMemberLit(trait.type.def, r.eq)}`;
  }
  if (trait.type.kind === 'scalar') {
    return `${x} == ${scalarLit(trait.type.name, r.eq)}`;
  }
  throw new Error(`${cap.file}: requires.eq on a ${trait.type.kind} trait`);
}

function commandSignature(cap: Capability, cmd: Command): string {
  const n = capNames(cap);
  const ret = cmd.result ? `std::expected<${n.result(cmd)}, Err>` : 'Status';
  const params = cmd.fields.length > 0 ? `const ${n.args(cmd)} &args` : '';
  return `${ret} ${cppIdent(cmd.name)}(${params})`;
}

function capHeader(cap: Capability): string {
  checkCapNames(cap);
  const n = capNames(cap);
  const P = cap.pascalName;
  const c = new Code();
  c.line(`${GENERATED} Source: ${cap.file}`);
  c.lines(docLines(`${cap.name} ${cap.version.major}.${cap.version.minor}: ${oneLine(cap.summary)}`));
  c.line('#pragma once').line();
  c.lines(['#include <cstddef>', '#include <cstdint>', '#include <expected>', '#include <span>', '#include <string_view>']).line();
  c.lines(['#include "codec_support.hpp"', '#include "fr/base.hpp"', '#include "fr/cap/capability.hpp"', '#include "fr/wire.hpp"']).line();
  c.line('namespace fr::cap {').line();

  for (const e of cap.enums) {
    emitEnumDecl(c, e);
  }

  if (cap.config.length > 0) {
    c.line('// Config: profile-time service parameters (not on the wire); defaults from the YAML.');
    c.open(`struct ${n.config}`, () => {
      for (const e of cap.config) {
        c.line(`${declare(e.type, cppIdent(e.name), e.default)}${fieldNote(e)}`);
      }
    }, '};');
    c.line();
  }

  for (const s of [...capTypeSpecs(cap), ...capStructs(cap)]) {
    emitStructDecl(c, s);
  }

  if (cap.properties.length > 0) {
    c.line('// STATE bodies: the property value as field 1, omitted when zero.');
    for (const p of cap.properties) {
      const f = stateFns(cap, p);
      c.line(`inline constexpr size_t ${f.max} = ${fieldWireMax(p.field)};`);
      c.line(`size_t ${f.encode}(${paramCpp(p.type)}v, fr::wire::Writer &w);`);
      c.line(`std::expected<${typeCpp(p.type)}, fr::wire::DecodeErr> ${f.decode}(std::span<const uint8_t> in);`);
    }
    c.line();
  }

  c.lines(docLines(cap.doc ? `${oneLine(cap.summary)} ${cap.doc}` : cap.summary));
  c.fn(`class ${P} : public Capability`, () => {
    c.dedent().line('public:').indent();
    c.line(`static constexpr uint16_t kId = ${hex(cap.id, 4)};`);
    c.line(`static constexpr Version kVersion{${cap.version.major}, ${cap.version.minor}};`);
    // Design m2-c3-inputs D8: the emit_* hand it to the Sink, which stamps an ordered port's events with port_seq.
    c.line(`static constexpr bool kOrdered = ${cap.ordered ? 'true' : 'false'};  // true: its events carry EXT port_seq (YAML ordered)`);
    if (cap.commands.length + cap.events.length + cap.properties.length > 0) {
      c.line();
      c.line('// Member ids (the envelope `kind`).');
      for (const cmd of cap.commands) {
        c.line(`static constexpr uint8_t kCmd${pascalCase(cmd.name)} = ${cmd.id};`);
      }
      for (const ev of cap.events) {
        c.line(`static constexpr uint8_t kEvent${pascalCase(ev.name)} = ${ev.id};`);
      }
      for (const p of cap.properties) {
        c.line(`static constexpr uint8_t kProp${pascalCase(p.name)} = ${p.id};`);
      }
    }
    c.line();
    c.line('uint16_t cap_id() const final { return kId; }');
    c.line('Version version() const final { return kVersion; }');
    c.line(`const char *type_name() const final { return ${cString(cap.name)}; }`);

    if (cap.commands.length > 0) {
      c.line();
      c.line('// Commands. Generated dispatch decodes the arguments (defaults applied) and refuses what valid()');
      c.line('// rejects, so implementations see only in-range values and known enum members.');
      for (const cmd of cap.commands) {
        const test = cmd.visibility === 'test';
        if (test) {
          c.pp('#if FR_TEST_HOOKS');
        }
        const note = `${cmd.delivery}${cmd.idempotent ? ', idempotent' : ''}${cmd.bulk ? ', bulk' : ''}${test ? ', visibility: test' : ''}`;
        c.lines(docLines(cmd.doc));
        c.line(`virtual ${commandSignature(cap, cmd)} = 0;  // ${note}`);
        if (test) {
          c.pp('#endif');
        }
      }
    }

    if (cap.properties.length > 0) {
      c.line();
      c.line('// Property getters (report_all re-reports them).');
      for (const p of cap.properties) {
        const req = p.requires ? `  // requires trait ${p.requires.trait}${p.requires.eq !== undefined ? ` == ${String(p.requires.eq)}` : ''}` : '';
        c.line(`virtual ${typeCpp(p.type)} ${cppIdent(p.name)}() const = 0;${req}`);
      }
    }
    if (cap.traits.length > 0) {
      c.line(`virtual ${n.traits} traits() const = 0;`);
    }

    c.line();
    c.line('Status dispatch(uint8_t cmd_id, std::span<const uint8_t> args, Reply &reply) final;');
    c.line('void report_all() final;');
    c.line('void encode_traits(fr::wire::Writer &w) const final;');
    c.line();
    c.dedent().line('protected:').indent();
    c.line(`~${P}() = default;`);
    if (cap.events.length > 0) {
      c.line();
      c.line('// Events: encoded and handed to the Sink; a body that would not fit is dropped. `at` is when it');
      c.line('// happened (the EVENT t_us), e.g. an edge timestamp; kNowUs stamps the emission time.');
      for (const ev of cap.events) {
        const req = ev.requires ? `, requires trait ${ev.requires.trait}` : '';
        c.line(`void emit_${ev.name}(const ${n.event(ev)} &e, TimeUs at = kNowUs);  // ${ev.priority}${req}`);
      }
    }
    if (cap.properties.length > 0) {
      c.line();
      c.line('// Properties: STATE frames; call on change (`at` as for events).');
      for (const p of cap.properties) {
        c.line(`void report_${p.name}(${paramCpp(p.type)}v, TimeUs at = kNowUs);  // property id ${p.id}`);
      }
    }
  }, '};');
  c.line().line('}  // namespace fr::cap');
  return c.text();
}

function capSource(cap: Capability): string {
  const n = capNames(cap);
  const P = cap.pascalName;
  const structs = [...capTypeSpecs(cap), ...capStructs(cap)];
  const c = new Code();
  c.line(`${GENERATED} Source: ${cap.file}`);
  c.line(`#include "${cap.shortName}.hpp"`).line();
  const allFields = [...structs.flatMap((s) => s.fields), ...cap.properties.map((p) => p.field)];
  const inc = new Set(cppIncludesFor(allFields));
  if (allFields.some((f) => f.type.kind === 'array' && f.type.element.kind !== 'scalar')) {
    inc.add('<algorithm>');
  }
  c.lines([...inc].sort().map((i) => `#include ${i}`)).line();
  c.line('namespace fr::cap {').line();

  for (const e of cap.enums) {
    emitEnumDefs(c, e);
  }
  for (const s of structs) {
    emitStructDefs(c, s);
  }
  for (const p of cap.properties) {
    const f = stateFns(cap, p);
    c.fn(`size_t ${f.encode}(${paramCpp(p.type)}v, fr::wire::Writer &w)`, () => {
      c.line('const size_t start = w.size();');
      encodeField(c, p.field, 'v', null);
      c.line('return w.size() - start;');
    });
    c.line();
    c.fn(`std::expected<${typeCpp(p.type)}, fr::wire::DecodeErr> ${f.decode}(std::span<const uint8_t> in)`, () => {
      c.line(declare(p.type, 'v', undefined));
      c.line('fr::wire::Reader r(in);');
      emitDecodeLoop(c, [{ f: p.field, x: 'v', has: null }]);
      c.open('if (!r.ok())', () => c.line('return std::unexpected(r.error());'));
      c.line('return v;');
    });
    c.line();
  }

  // dispatch: parameters unused outside test-only commands are [[maybe_unused]] (FR_TEST_HOOKS=0 builds).
  const argsUse = (cmds: Command[]) => cmds.length > 0;
  const replyUse = (cmds: Command[]) => cmds.some((x) => x.result !== null);
  const pub = cap.commands.filter((x) => x.visibility !== 'test');
  const param = (used: boolean, usedAlways: boolean, decl: string, name: string) => (!used ? decl : `${usedAlways ? '' : '[[maybe_unused]] '}${decl}${name}`);
  const argsP = param(argsUse(cap.commands), argsUse(pub), 'std::span<const uint8_t> ', 'args');
  const replyP = param(replyUse(cap.commands), replyUse(pub), 'Reply &', 'reply');
  const cmdP = cap.commands.length > 0 ? 'uint8_t cmd_id' : 'uint8_t';
  c.fn(`Status ${P}::dispatch(${cmdP}, ${argsP.trimEnd()}, ${replyP.trimEnd()})`, () => {
    if (cap.commands.length === 0) {
      c.line('return std::unexpected(Err::unsupported);');
      return;
    }
    c.open('switch (cmd_id)', () => {
      c.dedent();
      for (const cmd of cap.commands) {
        const test = cmd.visibility === 'test';
        if (test) {
          c.pp('#if FR_TEST_HOOKS');
        }
        const k = `kCmd${pascalCase(cmd.name)}`;
        const call = `${cppIdent(cmd.name)}(${cmd.fields.length > 0 ? '*a' : ''})`;
        c.line(`case ${k}: {`).indent();
        if (cmd.fields.length > 0) {
          c.line(`const auto a = decode_${cap.shortName}_${cmd.name}_args(args);`);
          c.open('if (!a || !valid(*a))', () => c.line('return std::unexpected(Err::invalid_args);'));
        } else {
          c.open('if (!fr::proto::decode_empty(args))', () => c.line('return std::unexpected(Err::invalid_args);'));
        }
        if (cmd.result) {
          c.line(`const auto r = ${call};`);
          c.open('if (!r)', () => c.line('return std::unexpected(r.error());'));
          c.line('encode(*r, reply.fields());');
          c.line("// Fields beyond the caller's buffer (realtime or bulk): FAILED with no fields, never truncated ones.");
          c.open('if (reply.fields().overflow())', () => c.line('reply.clear();').line('return std::unexpected(Err::failed);'));
          c.line('return {};');
        } else {
          c.line(`return ${call};`);
        }
        c.dedent().line('}');
        if (test) {
          c.pp('#endif');
        }
      }
      c.line('default:').indent().line('return std::unexpected(Err::unsupported);').dedent();
      c.indent();
    });
  });
  c.line();

  c.fn(`void ${P}::report_all()`, () => {
    if (cap.properties.some((p) => p.requires)) {
      c.line(`const ${n.traits} t = traits();`);
    }
    for (const p of cap.properties) {
      const report = `report_${p.name}(${cppIdent(p.name)}());`;
      if (p.requires) {
        c.open(`if (${requiresExpr(cap, p.requires, 't')})`, () => c.line(report));
      } else {
        c.line(report);
      }
    }
  });
  c.line();
  c.fn(`void ${P}::encode_traits(fr::wire::Writer &${cap.traits.length > 0 ? 'w' : ''}) const`, () => {
    if (cap.traits.length > 0) {
      c.line('encode(traits(), w);');
    }
  });
  c.line();

  for (const ev of cap.events) {
    const name = n.event(ev);
    const prio = `Priority::${ev.priority}`;
    const k = `kEvent${pascalCase(ev.name)}`;
    if (ev.fields.length === 0) {
      c.fn(`void ${P}::emit_${ev.name}(const ${name} &, TimeUs at)`, () => {
        c.open('if (sink_ != nullptr)', () => c.line(`sink_->event(port_, ${k}, ${prio}, {}, at, kOrdered);`));
      });
    } else {
      c.fn(`void ${P}::emit_${ev.name}(const ${name} &e, TimeUs at)`, () => {
        c.open('if (sink_ == nullptr)', () => c.line('return;'));
        c.line(`uint8_t buf[${name}::kMaxSize];`);
        c.line('fr::wire::Writer w(buf, sizeof(buf));');
        c.line('encode(e, w);');
        if (hasViews(ev.fields)) {
          // kMaxSize bounds every value the field types allow, except a view longer than its max.
          c.open('if (!w.overflow())', () => c.line(`sink_->event(port_, ${k}, ${prio}, w.bytes(), at, kOrdered);`));
        } else {
          c.line(`sink_->event(port_, ${k}, ${prio}, w.bytes(), at, kOrdered);`);
        }
      });
    }
    c.line();
  }

  for (const p of cap.properties) {
    const f = stateFns(cap, p);
    const k = `kProp${pascalCase(p.name)}`;
    c.fn(`void ${P}::report_${p.name}(${paramCpp(p.type)}v, TimeUs at)`, () => {
      c.open('if (sink_ == nullptr)', () => c.line('return;'));
      c.line(`uint8_t buf[${f.max}];`);
      c.line('fr::wire::Writer w(buf, sizeof(buf));');
      c.line(`${f.encode}(v, w);`);
      if (p.type.kind === 'string' || p.type.kind === 'bytes') {
        c.open('if (!w.overflow())', () => c.line(`sink_->property(port_, ${k}, w.bytes(), at);`));
      } else {
        c.line(`sink_->property(port_, ${k}, w.bytes(), at);`);
      }
    });
    c.line();
  }

  c.trim().line().line('}  // namespace fr::cap');
  return c.text();
}

