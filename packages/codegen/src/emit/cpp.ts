/** Every C++ output of `fr gen` (design c2 §2, §4). Paths are repo-relative. */
export function emitCpp(model: Model, vectors: VectorCase[]): GeneratedFile[] {
  // vectors may be GoldenVector cases (decodeOnly, error), a superset of VectorCase.
  const files: GeneratedFile[] = [
    { path: `${CPP_PROTO_GEN_DIR}/codec_support.hpp`, content: codecSupportHeader() },
    { path: `${CPP_PROTO_GEN_DIR}/protocol.hpp`, content: protocolHeader(model) },
    { path: `${CPP_PROTO_GEN_DIR}/protocol.cpp`, content: protocolSource(model) },
    { path: `${CPP_PROTO_GEN_DIR}/messages.hpp`, content: messagesHeader(model) },
    { path: `${CPP_PROTO_GEN_DIR}/messages.cpp`, content: messagesSource(model) },
    { path: `${CPP_PROTO_GEN_DIR}/serial.hpp`, content: serialHeader(model) },
    { path: `${CPP_PROTO_GEN_DIR}/serial.cpp`, content: serialSource(model) },
  ];
  for (const cap of model.capabilities) {
    files.push({ path: `${CPP_CAPS_GEN_DIR}/${cap.shortName}.hpp`, content: capHeader(cap) });
    files.push({ path: `${CPP_CAPS_GEN_DIR}/${cap.shortName}.cpp`, content: capSource(cap) });
  }
  files.push(
    { path: `${CPP_CAPS_GEN_DIR}/catalog.hpp`, content: catalogHeader(model) },
    { path: `${CPP_CAPS_GEN_DIR}/catalog.cpp`, content: catalogSource(model) },
    { path: `${CPP_CAPS_GEN_DIR}/diag_json.hpp`, content: diagJsonHeader() },
    { path: `${CPP_CAPS_GEN_DIR}/diag_json.cpp`, content: diagJsonSource(model) },
    { path: `${CPP_HOST_GEN_DIR}/decoders.inc`, content: decodersInc(model) },
    { path: `${CPP_HOST_GEN_DIR}/vectors.inc`, content: vectorsInc(model, vectors as Vector[]) },
  );
  return files;
}
