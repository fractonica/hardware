// C++ emitter for `fr gen` (spec 07 §7.6-7.7, design c2 §4). Writes:
//   firmware/components/fr_proto/gen/  protocol constants and enums, system message structs + codecs
//   firmware/components/fr_caps/gen/   per capability: enums, Traits/Config/Args/Result/Event structs,
//                                      codecs, the abstract interface with generated dispatch; catalog;
//                                      diag JSON codecs (FR_TEST_HOOKS builds only)
//   firmware/test/host/gen/            golden vectors and the decoder list for the host suite
// The output is a pure function of the model and the vectors, so `fr gen --check` can compare bytes.
//
// Codec rules shared with the TS emitter and pinned by the golden vectors (both sides must accept and
// reject the same inputs with the same DecodeErr):
// - encode writes fields in ascending id order; `implicit` fields are omitted when zero, `always` fields
//   are always written, `optional` fields iff has_<field>; encoders do not check ranges;
// - decode starts from the struct's defaults, skips unknown ids, and the last occurrence wins; values are
//   checked against their type only: enums are open (any value of the underlying type) and `range` is
//   not a codec rule. valid() applies the schema (members, ranges; an implicit zero is exempt), and
//   dispatch and the diag JSON codecs refuse what it rejects, as the TS JSON accessors do;
// - array<scalar|enum> is one packed field (a later occurrence replaces the earlier one); array<Msg> is
//   one field per element (occurrences append); element max+1 is too_long before it is read.

