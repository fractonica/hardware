/** `from_json_*` call that parses JSON item `j` into lvalue `x` (a `bool` expression). */
function fromJsonExpr(t: TypeRef, j: string, x: string, bytesBuf: string | null): string {
  switch (t.kind) {
    case 'scalar':
      switch (t.name) {
        case 'bool':
          return `from_json_bool(${j}, ${x})`;
        case 'f32':
          return `from_json_f32(${j}, ${x})`;
        case 'u64':
          return `from_json_u64(${j}, ${x})`;
        case 'i8':
          return `from_json_sint(${j}, -0x80, 0x7F, ${x})`;
        case 'i16':
          return `from_json_sint(${j}, -0x8000, 0x7FFF, ${x})`;
        case 'i32':
          return `from_json_sint(${j}, INT32_MIN, INT32_MAX, ${x})`;
        case 'u8':
          return `from_json_uint(${j}, 0xFF, ${x})`;
        case 'u16':
          return `from_json_uint(${j}, 0xFFFF, ${x})`;
        default:
          return `from_json_uint(${j}, 0xFFFFFFFF, ${x})`;
      }
    case 'enum':
      return `from_json_enum(${j}, ${x})`;
    case 'string':
      return `from_json_string(${j}, ${t.max}, ${x})`;
    case 'bytes':
      return `from_json_bytes(${j}, ${bytesBuf}, ${x})`;
    case 'array': {
      const el = t.element;
      if (el.kind === 'struct' && el.def.scope === 'protocol') {
        throw new Error('capability fields cannot hold protocol structs');
      }
      const elType: TypeRef = el.kind === 'scalar' ? { kind: 'scalar', name: el.name } : el;
      return `from_json_array(${j}, ${x}, [](const cJSON *e, ${elementCpp(el)} &out) { return ${fromJsonExpr(elType, 'e', 'out', null)}; })`;
    }
    case 'struct':
      if (t.def.scope === 'protocol') {
        throw new Error('capability fields cannot hold protocol structs');
      }
      return `from_json_${snakeOf(structCpp(t.def))}(${j}, ${x})`;
  }
}

function toJsonExpr(t: TypeRef, x: string): string {
  switch (t.kind) {
    case 'scalar':
      if (t.name === 'bool') {
        return `json_bool(${x})`;
      }
      return t.name === 'u64' ? `json_u64(${x})` : `json_number(${x})`;
    case 'enum':
      return `json_enum(${x})`;
    case 'string':
      return `json_string(${x})`;
    case 'bytes':
      return `json_bytes(${x})`;
    case 'array': {
      const el = t.element;
      if (el.kind === 'struct') {
        if (el.def.scope === 'protocol') {
          throw new Error('capability fields cannot hold protocol structs');
        }
        return `json_array(${x}, [](const ${structCpp(el.def)} &e) { return to_json(e); })`;
      }
      const elType: TypeRef = el.kind === 'scalar' ? { kind: 'scalar', name: el.name } : el;
      return `json_array(${x}, [](${elementCpp(el)} e) { return ${toJsonExpr(elType, 'e')}; })`;
    }
    case 'struct':
      return `to_json(${x})`;
  }
}

