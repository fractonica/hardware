// Names the hand-written runtime defines (fr/envelope.hpp, fr/serial_line.hpp); gen checks them with
// static_assert and defines only what is missing.
const RUNTIME_FLAGS = new Set(['SEC', 'ACK_REQ', 'FRAG', 'RELAYED', 'LATEST', 'URGENT', 'BULK', 'EXT']);
const RUNTIME_CLASSES = new Set(['NET', 'PRESENCE', 'ACK', 'EVENT', 'CMD', 'RESULT', 'STATE', 'MSG', 'LOG', 'OTA', 'TIME']);
const RUNTIME_SERIAL = new Set(['ENV', 'GW_RX', 'GW_TX', 'GW_TX_DONE', 'GW_STATUS', 'GW_CMD', 'GW_RSP', 'LINK_PING', 'LINK_PONG']);

function clsConst(name: string): string {
  return `${RUNTIME_CLASSES.has(name) ? 'fr::wire::' : ''}kCls${pascalUpper(name)}`;
}

function kindConst(cls: string, kind: string): string {
  return `kKind${pascalUpper(cls)}${pascalUpper(kind)}`;
}

function messageStructName(m: Message): string {
  return `${pascalUpper(m.cls)}${pascalUpper(m.kindName)}`;
}

function messageSpecs(model: Model): StructSpec[] {
  const p = model.protocol;
  const types: StructSpec[] = p.types.map((t: StructDef) => ({
    name: t.name,
    fields: t.fields,
    decode: `decode_${snakeOf(t.name)}`,
    comment: [`// ${t.name} (protocol type).`],
    statics: [],
    validate: false,
  }));
  const messages: StructSpec[] = p.messages.map((m) => {
    const name = messageStructName(m);
    const statics = [`static constexpr uint8_t kCls = ${clsConst(m.cls)};`];
    if (m.kind !== null) {
      statics.push(`static constexpr uint8_t kKind = ${kindConst(m.cls, m.kindName)};`);
    }
    return {
      name,
      fields: m.fields,
      decode: `decode_${snakeOf(name)}`,
      comment: [m.kind === null ? `// ${m.key}: the body of every ${m.cls} kind.` : `// ${m.key}`],
      statics,
      validate: false,
    };
  });
  return [...types, ...messages];
}

function protocolHeader(model: Model): string {
  const p = model.protocol;
  const c = new Code();
  c.line(`${GENERATED} Source: ${p.file}`);
  c.line('// Protocol constants and enums (spec 05 §5.5-5.8). The hand-written runtime (fr/envelope.hpp,');
  c.line('// fr/serial_line.hpp) owns the header, flag, class and serial-type constants; this file checks them');
  c.line('// against the schema and adds the rest.');
  c.line('#pragma once').line();
  c.lines(['#include <cstddef>', '#include <cstdint>', '#include <string_view>']).line();
  c.lines(['#include "fr/base.hpp"', '#include "fr/envelope.hpp"', '#include "fr/serial_line.hpp"']).line();
  c.line('namespace fr::proto {').line();
  c.line(`inline constexpr uint8_t kProtocolVersion = ${p.version};`).line();

  c.line('// Header (18 bytes, little-endian).');
  const magic = p.header.find((f) => f.name === 'magic_ver')?.value ?? 0xa1;
  c.line(`static_assert(fr::wire::kMagicVer == ${hex(magic, 2)});`);
  c.line(`static_assert(fr::wire::kHeaderSize == ${p.headerSize});`);
  c.line(`inline constexpr size_t kFragHeaderSize = ${p.frag.reduce((n, f) => n + f.size, 0)};`).line();

  c.line('// Flag masks.');
  for (const f of p.flags) {
    const n = `kFlag${pascalUpper(f.name)}`;
    c.line(RUNTIME_FLAGS.has(f.name) ? `static_assert(fr::wire::${n} == ${hex(f.mask, 2)});` : `inline constexpr uint8_t ${n} = ${hex(f.mask, 2)};`);
  }
  c.line();

  c.line('// Classes and their raw prefix sizes.');
  for (const cl of p.classes) {
    if (!RUNTIME_CLASSES.has(cl.name)) {
      c.line(`inline constexpr uint8_t kCls${pascalUpper(cl.name)} = ${hex(cl.code, 2)};`);
    } else {
      c.line(`static_assert(${clsConst(cl.name)} == ${hex(cl.code, 2)});`);
    }
    c.line(`static_assert(fr::wire::prefix_size(${clsConst(cl.name)}) == ${cl.prefixSize});`);
  }
  c.line();

  c.line('// Kinds; EVENT, CMD, RESULT and STATE carry capability member ids instead.');
  for (const cl of p.classes) {
    if (cl.kinds === 'capability') {
      continue;
    }
    for (const k of cl.kinds) {
      c.line(`inline constexpr uint8_t ${kindConst(cl.name, k.name)} = ${k.value};`);
    }
  }
  c.line();

  const ports = p.classes.filter((cl) => cl.port !== undefined);
  if (ports.length > 0) {
    c.line('// Classes bound to a port.');
    for (const cl of ports) {
      c.line(`inline constexpr uint8_t kCls${pascalUpper(cl.name)}Port = ${cl.port};`);
    }
    c.line();
  }

  c.line('// Status codes (RESULT, ACK, REJECT): 0 is OK, every other code is the fr::Err of that value.');
  for (const s of p.status) {
    if (s.value === 0) {
      c.line(`inline constexpr uint8_t kStatus${pascalUpper(s.name)} = 0;`);
    } else {
      c.line(`static_assert(static_cast<uint8_t>(fr::Err::${snakeUpper(s.name)}) == ${s.value});`);
    }
  }
  c.line();

  const a = p.addresses;
  c.line('// Addresses.');
  c.line(`inline constexpr uint16_t kAddrHub = ${hex(a.hub, 4)};`);
  c.line(`inline constexpr uint16_t kAddrNodesFirst = ${hex(a.nodes[0], 4)};`);
  c.line(`inline constexpr uint16_t kAddrNodesLast = ${hex(a.nodes[1], 4)};`);
  c.line(`inline constexpr uint16_t kAddrGroupsFirst = ${hex(a.groups[0], 4)};`);
  c.line(`inline constexpr uint16_t kAddrGroupsLast = ${hex(a.groups[1], 4)};`);
  for (const [name, v] of Object.entries(a.wellKnown)) {
    c.line(`inline constexpr uint16_t kAddr${pascalCase(name)} = ${hex(v, 4)};`);
  }
  c.line(`inline constexpr uint16_t kAddrUnassigned = ${hex(a.unassigned, 4)};`);
  c.line(`inline constexpr uint16_t kAddrBroadcast = ${hex(a.broadcast, 4)};`).line();

  c.line('// Ports.');
  c.line(`inline constexpr uint8_t kPortNode = ${p.ports.node};`);
  c.line(`inline constexpr uint8_t kPortOta = ${p.ports.ota};`);
  c.line(`inline constexpr uint8_t kPortDiag = ${p.ports.diag};`);
  c.line(`inline constexpr uint8_t kPortCapsFirst = ${p.ports.capabilities[0]};`);
  c.line(`inline constexpr uint8_t kPortCapsLast = ${p.ports.capabilities[1]};`).line();

  c.line('// MTU and the realtime payload budget (07 §7.5).');
  c.line(`inline constexpr size_t kMtuRealtime = ${p.mtu.realtime};`);
  c.line(`inline constexpr size_t kMtuBulk = ${p.mtu.bulk};`);
  c.line(`inline constexpr size_t kRealtimePayloadBudget = ${p.mtu.realtimePayloadBudget};`).line();

  // The runtime decides which TLVs it knows (unsupported_ext, bad_ext), so it owns the types: a schema type
  // the runtime lacks stops the build here.
  c.line('// EXT TLV types (fr/envelope.hpp) and their value sizes; types >= 0x80 are critical.');
  for (const t of p.extTlvs) {
    const n = `fr::wire::kExt${pascalCase(t.name)}`;
    c.line(`static_assert(${n} == ${hex(t.type, 2)} && fr::wire::ext_value_size(${n}) == ${LAYOUT_BYTES[t.valueType]});`);
  }
  c.line();

  c.line('// Serial line framing.');
  c.line(`static_assert(fr::wire::kLinePrefix == ${cString(p.serial.prefix)});`);
  c.line(`static_assert(fr::wire::kMaxLine == ${p.serial.maxLine});`);
  for (const t of p.serial.types) {
    const n = `kSerial${pascalUpper(t.name)}`;
    c.line(RUNTIME_SERIAL.has(t.name) ? `static_assert(fr::wire::${n} == ${hex(t.value, 2)});` : `inline constexpr uint8_t ${n} = ${hex(t.value, 2)};`);
  }
  c.line();

  c.line('// Enums.');
  for (const e of p.enums) {
    emitEnumDecl(c, e);
  }
  c.trim().line().line('}  // namespace fr::proto');
  return c.text();
}

