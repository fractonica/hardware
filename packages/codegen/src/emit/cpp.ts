// ---- code builder ----

class Code {
  private readonly out: string[] = [];
  private depth = 0;

  line(text = ''): this {
    this.out.push(text === '' ? '' : `${'    '.repeat(this.depth)}${text}`);
    return this;
  }

  /** A preprocessor line, always in column 0. */
  pp(text: string): this {
    this.out.push(text);
    return this;
  }

  lines(texts: readonly string[]): this {
    for (const t of texts) {
      this.line(t);
    }
    return this;
  }

  indent(): this {
    this.depth++;
    return this;
  }

  dedent(): this {
    this.depth--;
    return this;
  }

  /** Function or class: the brace goes on its own line. */
  fn(head: string, body: () => void, close = '}'): this {
    this.line(head).line('{').indent();
    body();
    return this.dedent().line(close);
  }

  /** Control flow, structs, namespaces: `head {`. */
  open(head: string, body: () => void, close = '}'): this {
    this.line(`${head} {`).indent();
    body();
    return this.dedent().line(close);
  }

  /** A bare `{ ... }` scope. */
  block(body: () => void): this {
    this.line('{').indent();
    body();
    return this.dedent().line('}');
  }

  /** The position of the next line, for insert(). */
  mark(): number {
    return this.out.length;
  }

  /** Inserts a line at a mark (for values known only after the rest is generated). */
  insert(at: number, text: string): this {
    this.out.splice(at, 0, text);
    return this;
  }

  /** Drops a trailing blank line (before a closing brace or the end of a file). */
  trim(): this {
    while (this.out.length > 0 && this.out[this.out.length - 1] === '') {
      this.out.pop();
    }
    return this;
  }

  text(): string {
    this.trim();
    return `${this.out.join('\n')}\n`;
  }
}

/** Collapses a YAML doc to one paragraph and wraps it into `//` comment lines. */
function docLines(doc: string | undefined, width = 100): string[] {
  if (!doc) {
    return [];
  }
  const words = doc.trim().split(/\s+/);
  const out: string[] = [];
  let cur = '';
  for (const w of words) {
    if (cur && cur.length + 1 + w.length > width) {
      out.push(`// ${cur}`);
      cur = w;
    } else {
      cur = cur ? `${cur} ${w}` : w;
    }
  }
  if (cur) {
    out.push(`// ${cur}`);
  }
  return out;
}

function oneLine(doc: string | undefined): string {
  return doc ? doc.trim().replace(/\s+/g, ' ') : '';
}

function hex(n: number, width: number): string {
  return `0x${n.toString(16).toUpperCase().padStart(width, '0')}`;
}

