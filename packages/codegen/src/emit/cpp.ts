const DECODE_ERR_NAMES: ReadonlySet<string> = new Set(DECODE_ERRORS);

function vectorsInc(model: Model, vectors: readonly Vector[]): string {
  const c = new Code();
  let calls = 0;
  const decoders = decoderEntries(model);
  const vw = new VectorWriter(c);

  /** `x.field = ...;` for a layout serial body's JSON value (macs and env as hex, enums by name or number). */
  const assignLayout = (b: SerialBody, value: unknown, where: string) => {
    if (value === null || typeof value !== 'object' || Array.isArray(value)) {
      throw new Error(`${where}: expected an object, got ${JSON.stringify(value)}`);
    }
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      if (b.envelope && k === 'env') {
        c.line(`x.env = ${vw.valueExpr({ kind: 'bytes', max: 1 << 16 }, v, `${where}.env`)};`);
        continue;
      }
      const f = b.layout.find((x) => x.name === k);
      if (!f) {
        throw new Error(`${where}: unknown field '${k}'`);
      }
      const x = `x.${cppIdent(f.name)}`;
      if (f.type === 'mac') {
        const bytes = typeof v === 'string' ? hexBytes(v) : [];
        if (bytes.length !== 6) {
          throw new Error(`${where}.${k}: expected 6 bytes of hex`);
        }
        c.line(`${x} = ${bytesInit(bytes)};`);
      } else if (f.type === 'enum') {
        c.line(`${x} = ${typeof v === 'number' ? `static_cast<${enumCpp(f.enum!)}>(${v})` : enumMemberLit(f.enum!, v)};`);
      } else {
        c.line(`${x} = ${scalarLit(f.type, v)};`);
      }
    }
  };

  /** Builds `x` from a message/cap/state value and calls v.value. */
  const emitValue = (name: string, type: string, value: unknown, hexLit: string, encode: boolean, where: string) => {
    const d = decoders.find((x) => x.type === type);
    if (!d) {
      throw new Error(`${where}: no generated codec for type ${type}`);
    }
    const layout = model.protocol.serial.bodies.find((x) => x.kind === 'layout' && x.name === type);
    if (d.encode) {
      const cap = model.capabilities.find((x) => type.startsWith(`${x.name}.`))!;
      const p = cap.properties.find((x) => type === `${cap.name}.${x.name}.state`)!;
      const obj = value !== null && typeof value === 'object' && !Array.isArray(value) ? (value as Record<string, unknown>) : null;
      const v = obj ? (obj[p.name] ?? obj.value) : value;
      const init = memberInit(p.type, undefined);
      c.line(init === null ? `${typeCpp(p.type)} x{};` : `${typeCpp(p.type)} x = ${init};`);
      if (v !== undefined) {
        c.line(`x = ${vw.valueExpr(p.type, v, `${where}.value`)};`);
      }
      c.line(`v.value(${cString(name)}, ${cString(type)}, x, ${d.encode}, ${d.decode}, ${hexLit}, ${encode});`);
    } else if (layout) {
      c.line(`${d.cpp} x{};`);
      assignLayout(layout, value ?? {}, where);
      c.line(`v.value(${cString(name)}, ${cString(type)}, x, enc, ${d.decode}, ${hexLit}, ${encode});`);
    } else {
      c.line(`${d.cpp} x{};`);
      vw.assign(fieldsOfType(model, type), value ?? {}, 'x', where);
      c.line(`v.value(${cString(name)}, ${cString(type)}, x, enc, ${d.decode}, ${hexLit}, ${encode});`);
    }
    calls++;
  };

  const errorDecoder = (vec: Vector, where: string): string => {
    switch (vec.kind) {
      case 'header':
        return 'fr::wire::unpack_header';
      case 'envelope':
        return 'fr::wire::unpack_envelope';
      case 'serial':
        return 'decode_serial';
      default: {
        const d = decoders.find((x) => x.type === vec.type);
        if (!d) {
          throw new Error(`${where}: no generated codec for type ${vec.type}`);
        }
        return d.decode;
      }
    }
  };

  const emitAll = () => {
    for (const vec of vectors) {
      const where = `vector ${vec.name}`;
      const name = cString(vec.name);
      const bytes = hexBytes(vec.hex);
      const hexLit = cString(hexOf(bytes));
      const encode = vec.decodeOnly !== true;
      c.line(`// ${vec.name} (${vec.kind} ${vec.type}${vec.error ? `, ${vec.error}` : vec.decodeOnly ? ', decode only' : ''})`);
      c.block(() => {
        if (vec.error !== undefined) {
          if (!DECODE_ERR_NAMES.has(vec.error)) {
            throw new Error(`${where}: unknown decode error ${vec.error}`);
          }
          c.line(`v.error(${name}, ${cString(vec.type)}, ${errorDecoder(vec, where)}, ${hexLit}, fr::wire::DecodeErr::${vec.error});`);
          calls++;
          return;
        }
        switch (vec.kind) {
          case 'message':
          case 'cap':
            emitValue(vec.name, vec.type, vec.value, hexLit, encode, where);
            break;
          case 'header': {
            const raw = vec.value as Record<string, unknown> | null;
            const h = headerFromValue(raw && typeof raw === 'object' && 'header' in raw ? raw.header : raw, bytes, where);
            emitHeaderValue(c, vw, h, 'h');
            c.line(`v.header(${name}, h, ${hexLit});`);
            calls++;
            break;
          }
          case 'envelope': {
            const env = unpackEnvelope(Uint8Array.from(bytes));
            if (!env.ok) {
              throw new Error(`${where}: envelope bytes do not decode (${env.error})`);
            }
            const raw = (vec.value !== null && typeof vec.value === 'object' ? vec.value : {}) as Record<string, unknown>;
            headerFromValue(raw.header ?? null, bytes, where);
            emitHeaderValue(c, vw, env.value.header, 'h');
            const p = env.value.prefix;
            c.line(`const uint32_t t_us = ${p.type === 'time' ? p.t_us : 0};`);
            c.line(`const fr::wire::ResultPrefix rp{${p.type === 'result' ? `${p.req_epoch}, ${p.req_seq}, ${p.status}` : ''}};`);
            c.line(`const auto body = ${vwBytes(vw, [...env.value.body])};`);
            c.line(`v.envelope(${name}, h, fr::wire::PrefixType::${p.type}, t_us, rp, body, ${hexLit});`);
            calls++;
            if (typeof raw.body_type === 'string') {
              // The body as its own vector: what the envelope carries is the typed value.
              c.block(() => emitValue(`${vec.name}/body`, raw.body_type as string, raw.body_value ?? {}, cString(hexOf(env.value.body)), true, `${where}.body`));
            }
            break;
          }
          case 'serial': {
            const s = serialFromVector(model, vec, bytes, where);
            c.line(`const auto body = ${vwBytes(vw, s.body)};`);
            c.line(`v.serial(${name}, ${hex(s.type, 2)}, body, ${cString(s.line)}, ${cString(s.input)}, ${encode});`);
            calls++;
            break;
          }
        }
      });
    }
  };

  c.line(`${GENERATED} Source: schema/vectors/*.json`);
  c.line('// Golden vectors for tests/vectors_test.cpp and the fuzz corpora. fr_vectors::for_each(v) calls, per case:');
  c.line('//   v.value(name, type, value, encode_fn, decode_fn, hex, encode)  message, capability struct, STATE body;');
  c.line('//                                                                  encode false: decode only');
  c.line('//   v.error(name, type, decode_fn, hex, DecodeErr)                 must fail to decode with that error');
  c.line('//   v.header(name, header, hex)');
  c.line('//   v.envelope(name, header, prefix_type, t_us, result_prefix, body, hex)');
  c.line('//   v.serial(name, frame_type, body, line, input, encode)          input: the line as given (terminators)');
  c.line('#pragma once').line();
  c.lines(['#include <cstddef>', '#include <cstdint>', '#include <expected>', '#include <span>', '#include <string_view>']).line();
  c.line('#include "fr/envelope.hpp"');
  c.line('#include "fr/serial_line.hpp"');
  c.line('#include "messages.hpp"');
  c.line('#include "serial.hpp"');
  c.lines(model.capabilities.map((cap) => `#include "${cap.shortName}.hpp"`)).line();
  c.line('namespace fr_vectors {').line();
  c.line('/** decode_line with its own scratch, shaped like the other decoders. */');
  c.fn('inline std::expected<fr::wire::SerialFrame, fr::wire::DecodeErr> decode_serial(std::span<const uint8_t> in)', () => {
    c.line('static uint8_t scratch[fr::wire::kMaxLineFrame];');
    c.line('return fr::wire::decode_line({reinterpret_cast<const char *>(in.data()), in.size()}, scratch);');
  });
  c.line();
  const countAt = c.mark();
  c.line();
  c.line('template <class V>');
  c.fn('void for_each(V &&v)', () => {
    c.line('using namespace fr::cap;');
    c.line('using namespace fr::proto;');
    c.line('[[maybe_unused]] const auto enc = [](const auto &x, fr::wire::Writer &w) { return encode(x, w); };');
    if (vectors.length === 0) {
      c.line('static_cast<void>(v);');
    }
    emitAll();
  });
  c.line().line('}  // namespace fr_vectors');
  c.insert(countAt, `inline constexpr size_t kCount = ${calls};`);
  return c.text();
}

function vwBytes(vw: VectorWriter, b: readonly number[]): string {
  return vw.valueExpr({ kind: 'bytes', max: Math.max(1, b.length) }, hexOf(b), 'body');
}

function fieldsOfType(model: Model, type: string): Field[] {
  const m = model.protocol.messages.find((x) => x.key === type);
  if (m) {
    return m.fields;
  }
  const t = model.protocol.types.find((x) => x.name === type);
  if (t) {
    return t.fields;
  }
  for (const cap of model.capabilities) {
    for (const s of capStructs(cap)) {
      if (vectorTypeOf(cap, s) === type) {
        return s.fields;
      }
    }
    if (cap.commands.some((x) => x.fields.length === 0 && type === `${cap.name}.${x.name}.args`)) {
      return [];
    }
  }
  throw new Error(`no generated struct for type ${type}`);
}

/**
 * A serial vector as (frame type, body, line). The value may carry `line`, or `type` (code or name) and
 * `body` (hex); what is missing comes from the type string and the vector bytes, which may be the
 * line's characters, the frame (type | body | crc) or the body.
 */
function serialFromVector(model: Model, vec: VectorCase, bytes: number[], where: string): { type: number; body: number[]; line: string; input: string } {
  const raw = (vec.value !== null && typeof vec.value === 'object' ? vec.value : {}) as Record<string, unknown>;
  const named = (n: unknown) => model.protocol.serial.types.find((t) => t.name === n)?.value;
  let type: number | undefined = typeof raw.type === 'number' ? raw.type : named(raw.type);
  let body: number[] | undefined = typeof raw.body === 'string' ? hexBytes(raw.body) : undefined;
  const ascii = String.fromCharCode(...bytes);
  const line = typeof raw.line === 'string' ? raw.line : ascii.startsWith(model.protocol.serial.prefix) ? ascii : undefined;
  if (line !== undefined) {
    const d = decodeSerialLine(line);
    if (!d.ok) {
      throw new Error(`${where}: the line does not decode (${d.error})`);
    }
    if ((type !== undefined && type !== d.value.type) || (body !== undefined && hexOf(body) !== hexOf(d.value.body))) {
      throw new Error(`${where}: the line disagrees with value.type/value.body`);
    }
    type = d.value.type;
    body = [...d.value.body];
  }
  type ??= named(vec.type.slice(vec.type.lastIndexOf('.') + 1));
  if (type === undefined) {
    throw new Error(`${where}: cannot tell the frame type of this serial vector`);
  }
  // Without a line, the bytes are the frame (type | body | crc) or the body.
  body ??= bytes.length >= 3 && bytes[0] === type ? bytes.slice(1, -2) : bytes;
  const canonical = encodeSerialLine(type, Uint8Array.from(body));
  const input = line ?? canonical;
  const frame = [type, ...body];
  const crc = crc16CcittFalse(Uint8Array.from(frame));
  const accepted = [hexOf(new TextEncoder().encode(input)), hexOf([...frame, crc & 0xff, crc >> 8]), hexOf(body)];
  if (!accepted.includes(hexOf(bytes))) {
    throw new Error(`${where}: the bytes are neither the line, the frame nor the body`);
  }
  return { type, body, line: canonical, input };
}

