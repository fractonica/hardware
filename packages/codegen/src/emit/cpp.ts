function codecSupportHeader(): string {
  return `${GENERATED}
// Support code for the generated codecs: fixed-capacity arrays (decoding never allocates), comparisons
// for bytes views and floats, and decoding of bodies without known fields.
#pragma once

#include <bit>
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <expected>
#include <initializer_list>
#include <span>

#include "fr/wire.hpp"

namespace fr::proto {

template <class T>
constexpr bool same(const T &a, const T &b)
{
    return a == b;
}

/** Bitwise, as on the wire: a NaN equals itself and -0.0 differs from 0.0. */
inline bool same(float a, float b)
{
    return std::bit_cast<uint32_t>(a) == std::bit_cast<uint32_t>(b);
}

/** bytes fields are views; decoded ones point into the decoder's input. */
inline bool equal_bytes(std::span<const uint8_t> a, std::span<const uint8_t> b)
{
    return a.size() == b.size() && (a.empty() || std::memcmp(a.data(), b.data(), a.size()) == 0);
}

/** array<T>{N} with inline storage. push_back refuses (returns false) when full. */
template <class T, size_t N>
class Array
{
public:
    static constexpr size_t kCapacity = N;

    constexpr Array() = default;
    constexpr Array(std::initializer_list<T> init)
    {
        for (const T &v : init) {
            push_back(v);
        }
    }

    constexpr size_t size() const { return size_; }
    constexpr bool empty() const { return size_ == 0; }
    constexpr bool full() const { return size_ == N; }
    constexpr void clear() { size_ = 0; }

    constexpr bool push_back(const T &v)
    {
        if (size_ == N) {
            return false;
        }
        items_[size_++] = v;
        return true;
    }

    constexpr T &operator[](size_t i) { return items_[i]; }
    constexpr const T &operator[](size_t i) const { return items_[i]; }
    constexpr T *begin() { return items_; }
    constexpr T *end() { return items_ + size_; }
    constexpr const T *begin() const { return items_; }
    constexpr const T *end() const { return items_ + size_; }
    constexpr std::span<const T> span() const { return {items_, size_}; }

    friend bool operator==(const Array &a, const Array &b)
    {
        if (a.size_ != b.size_) {
            return false;
        }
        for (size_t i = 0; i < a.size_; ++i) {
            if (!same(a.items_[i], b.items_[i])) {
                return false;
            }
        }
        return true;
    }

private:
    T items_[N]{};
    size_t size_ = 0;
};

/** The body of a command without fields (and of a RESULT without fields). */
struct Empty {
    static constexpr size_t kMaxSize = 0;

    bool operator==(const Empty &) const = default;
};

inline size_t encode(const Empty &, fr::wire::Writer &)
{
    return 0;
}

/** A body with no known fields: unknown fields are skipped, malformed input is still an error. */
inline std::expected<Empty, fr::wire::DecodeErr> decode_empty(std::span<const uint8_t> in)
{
    fr::wire::Reader r(in);
    while (r.next()) {
        r.skip();
    }
    if (!r.ok()) {
        return std::unexpected(r.error());
    }
    return Empty{};
}

}  // namespace fr::proto
`;
}

