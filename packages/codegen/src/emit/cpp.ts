interface DecoderEntry {
  ident: string;
  /** VectorCase.type */
  type: string;
  cpp: string;
  decode: string;
  /** Property states: the encode function (structs use the encode overload). */
  encode?: string;
}

function decoderEntries(model: Model): DecoderEntry[] {
  const out: DecoderEntry[] = [];
  for (const t of model.protocol.types) {
    out.push({ ident: snakeOf(t.name), type: t.name, cpp: `fr::proto::${t.name}`, decode: `fr::proto::decode_${snakeOf(t.name)}` });
  }
  for (const m of model.protocol.messages) {
    const name = messageStructName(m);
    out.push({ ident: snakeOf(name), type: m.key, cpp: `fr::proto::${name}`, decode: `fr::proto::decode_${snakeOf(name)}` });
  }
  // Layout serial bodies, under their serial type name (the protobuf ones are protocol types above).
  for (const b of model.protocol.serial.bodies.filter((x) => x.kind === 'layout')) {
    const name = serialStructName(b);
    out.push({ ident: snakeOf(name), type: b.name, cpp: `fr::proto::${name}`, decode: `fr::proto::${serialDecodeName(b)}` });
  }
  for (const cap of model.capabilities) {
    for (const s of capStructs(cap)) {
      out.push({ ident: s.decode.slice('decode_'.length), type: vectorTypeOf(cap, s), cpp: `fr::cap::${s.name}`, decode: `fr::cap::${s.decode}` });
    }
    // Commands without fields take no Args struct; their (empty) argument body is fr::proto::Empty.
    for (const cmd of cap.commands.filter((x) => x.fields.length === 0)) {
      out.push({ ident: `${cap.shortName}_${cmd.name}_args`, type: `${cap.name}.${cmd.name}.args`, cpp: 'fr::proto::Empty', decode: 'fr::proto::decode_empty' });
    }
    for (const p of cap.properties) {
      const f = stateFns(cap, p);
      out.push({ ident: `${cap.shortName}_${p.name}_state`, type: `${cap.name}.${p.name}.state`, cpp: qualifiedCpp(p.type), decode: `fr::cap::${f.decode}`, encode: `fr::cap::${f.encode}` });
    }
  }
  return out;
}

/** VectorCase.type of a capability struct: fr.led.blink.args, fr.diag.exec.result, fr.button.up.event, fr.led.traits. */
function vectorTypeOf(cap: Capability, s: StructSpec): string {
  const n = capNames(cap);
  if (s.name === n.traits) {
    return `${cap.name}.traits`;
  }
  for (const cmd of cap.commands) {
    if (s.name === n.args(cmd)) {
      return `${cap.name}.${cmd.name}.args`;
    }
    if (s.name === n.result(cmd)) {
      return `${cap.name}.${cmd.name}.result`;
    }
  }
  const ev = cap.events.find((e) => s.name === n.event(e))!;
  return `${cap.name}.${ev.name}.event`;
}

