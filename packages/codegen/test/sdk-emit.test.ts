// SDK emitter (design c6 §4.1): the committed packages/sdk/src/gen/caps.ts is current and deterministic,
// CAP_META mirrors the model, and names the SDK cannot carry fail generation: one that does not survive the
// snake_case <-> camelCase rule, an event field named like an event's own keys, an event and a property
// sharing a name, a command hiding an instance member.

import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';
import { parse, stringify } from 'yaml';

import { CATALOG_HASH } from '@fractonica/protocol/gen';
import { CAP_META, CATALOG_HASH as SDK_CATALOG_HASH } from '@fractonica/sdk';

import {
  buildModel,
  catalogHash,
  emitSdk,
  GENERATED_ROOTS,
  generateFiles,
  loadModel,
  readSchemaSources,
  SDK_GEN_DIR,
  sdkCamel,
  sdkSnake,
  type Model,
  type SchemaSources,
} from '@fractonica/codegen';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

type Yaml = Record<string, any>;

function edited(file: string, edit: (y: Yaml) => void): Model {
  const src: SchemaSources = readSchemaSources(ROOT);
  const f = [src.protocol, src.registry, ...src.capabilities].find((x) => x.path === file)!;
  const y = parse(f.text) as Yaml;
  edit(y);
  f.text = stringify(y);
  const r = buildModel(src);
  if (!r.ok) {
    throw new Error(`edited schema does not validate: ${r.issues.map((i) => i.message).join('; ')}`);
  }
  return r.model;
}

const emit = (m: Model) => emitSdk(m, catalogHash(m));

describe('emitSdk', () => {
  const model = loadModel(ROOT);

  it('the committed facades are current, deterministic and part of fr gen', () => {
    const files = emit(model);
    expect(files.map((f) => f.path)).toEqual([`${SDK_GEN_DIR}/caps.ts`]);
    for (const f of files) {
      const abs = join(ROOT, f.path);
      expect(existsSync(abs) && readFileSync(abs, 'utf8') === f.content, `${f.path} is stale: run fr gen`).toBe(true);
      expect(f.content.startsWith('// GENERATED by fr gen')).toBe(true);
    }
    expect(emit(loadModel(ROOT))).toEqual(files);
    expect(GENERATED_ROOTS).toContain(SDK_GEN_DIR);
    expect(generateFiles(ROOT).map((f) => f.path)).toContain(`${SDK_GEN_DIR}/caps.ts`);
  });

  it('CAP_META and CATALOG_HASH mirror the model', () => {
    expect(SDK_CATALOG_HASH).toBe(CATALOG_HASH);
    expect(Object.keys(CAP_META)).toEqual(model.capabilities.map((c) => c.name));
    for (const cap of model.capabilities) {
      const m = CAP_META[cap.name];
      expect(m.events).toEqual(cap.events.map((e) => e.name));
      expect(m.props).toEqual(cap.properties.map((p) => p.name));
      expect(Object.entries(m.commands).map(([name, c]) => [name, c.method, c.delivery, c.args ?? false, c.test ?? false])).toEqual(
        cap.commands.map((c) => [c.name, sdkCamel(c.name), c.delivery, c.fields.length > 0, c.visibility === 'test']),
      );
    }
    const caps = emit(model)[0].content;
    // Public commands become methods; test-only ones (inject) do not.
    expect(caps).toContain('blink(args?: LedBlinkArgs, opts?: CallOptions): Promise<CmdResult>;');
    expect(caps).toContain('set(args?: LedSetArgs): Promise<Sent>;');
    expect(caps).toContain('describe(opts?: CallOptions): Promise<CmdResult<NodeDescribeResult>>;');
    expect(caps).toContain('export interface ButtonClient {}');
    expect(caps).toMatch(/export interface ButtonEvents \{\n {2}down: ButtonDownFields;\n {2}up: ButtonUpFields;/);
    expect(caps).toMatch(/export interface LedState \{[^}]*on: boolean;[^}]*brightness\?: number;/);
  });

  it('maps names both ways by one rule', () => {
    expect(sdkCamel('held_ms')).toBe('heldMs');
    expect(sdkSnake('heldMs')).toBe('held_ms');
    expect(sdkCamel('long_press')).toBe('longPress');
    expect(sdkCamel('port9')).toBe('port9');
  });

  it('fails on names the SDK cannot carry', () => {
    const roundTrip = edited('schema/capabilities/button.cap.yaml', (y) => (y.events.up.fields.held_2 = { id: 2, type: 'u8' }));
    expect(() => emit(roundTrip)).toThrow(/held_2 does not survive the SDK's snake_case <-> camelCase mapping/);
    const metaKey = edited('schema/capabilities/button.cap.yaml', (y) => (y.events.click.fields.late = { id: 2, type: 'bool' }));
    expect(() => emit(metaKey)).toThrow(/events.click field late is late, a key every SDK event has/);
    const shared = edited('schema/capabilities/button.cap.yaml', (y) => (y.events.pressed = { id: 9, priority: 'normal' }));
    expect(() => emit(shared)).toThrow(/event pressed and property pressed/);
    const hides = edited('schema/capabilities/led.cap.yaml', (y) => (y.commands.state = { id: 9, delivery: 'reliable' }));
    expect(() => emit(hides)).toThrow(/command state would hide the SDK instance member state/);
    const clash = edited('schema/capabilities/led.cap.yaml', (y) => (y.types.SetArgs = { enum: { a: 0 } }));
    expect(() => emit(clash)).toThrow(/SDK type LedSetArgs .* collides with/);
  });
});
