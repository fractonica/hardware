// TS emitter and `fr gen` (generateAll): committed outputs are current, output is deterministic, the
// generated tables mirror the model, name clashes fail generation, and --check/write/orphan handling
// work on a scratch checkout.

import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { afterAll, describe, expect, it } from 'vitest';
import { parse, stringify } from 'yaml';

import { prefixType } from '@fractonica/protocol';
import { CAPS, CATALOG, CATALOG_HASH, CLASSES, MESSAGES, PROTOCOL_TYPES } from '@fractonica/protocol/gen';

import {
  buildModel,
  canonicalJson,
  catalogHash,
  emitTs,
  emitVectors,
  fnv1a32,
  generateAll,
  GENERATED_ROOTS,
  loadModel,
  readSchemaSources,
  TS_GEN_DIR,
  VECTORS_DIR,
  type Model,
  type SchemaSources,
} from '@fractonica/codegen';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

type Yaml = Record<string, any>;

function edited(file: string, edit: (y: Yaml) => void): Model {
  const src: SchemaSources = readSchemaSources(ROOT);
  const f = [src.protocol, src.registry, ...src.capabilities].find((x) => x.path === file)!;
  const y = parse(f.text) as Yaml;
  edit(y);
  f.text = stringify(y);
  const r = buildModel(src);
  if (!r.ok) {
    throw new Error(`edited schema does not validate: ${r.issues.map((i) => i.message).join('; ')}`);
  }
  return r.model;
}

describe('emitTs', () => {
  const model = loadModel(ROOT);

  it('the committed TS outputs and vectors are current', () => {
    const stale = [...emitTs(model), ...emitVectors(model).files].filter((f) => {
      const abs = join(ROOT, f.path);
      return !existsSync(abs) || readFileSync(abs, 'utf8') !== f.content;
    });
    expect(stale.map((f) => f.path)).toEqual([]);
  });

  it('is deterministic and stays inside its directory', () => {
    const a = emitTs(model);
    expect(emitTs(loadModel(ROOT))).toEqual(a);
    for (const f of a) {
      expect(f.path.startsWith(`${TS_GEN_DIR}/`)).toBe(true);
      expect(f.content.endsWith('\n')).toBe(true);
      if (f.path.endsWith('.ts')) {
        expect(f.content.startsWith('// GENERATED by fr gen')).toBe(true);
      } else {
        expect(() => JSON.parse(f.content)).not.toThrow();
      }
    }
    expect(a.map((f) => f.path)).toEqual(expect.arrayContaining([`${TS_GEN_DIR}/index.ts`, `${TS_GEN_DIR}/catalog.json`, `${TS_GEN_DIR}/schemas/fr.led.blink.args.json`]));
  });

  it('CATALOG_HASH is catalog_hash of the model and of CATALOG', () => {
    expect(CATALOG_HASH).toBe(catalogHash(model));
    expect(fnv1a32(canonicalJson(CATALOG))).toBe(CATALOG_HASH);
  });

  it('the generated tables mirror the model', () => {
    expect(CAPS.map((c) => [c.id, c.name, c.version])).toEqual(model.capabilities.map((c) => [c.id, c.name, c.version]));
    for (const cap of model.capabilities) {
      const g = CAPS.find((c) => c.id === cap.id)!;
      expect(g.commands.map((x) => [x.id, x.name, x.delivery, x.visibility, x.result !== null])).toEqual(
        cap.commands.map((x) => [x.id, x.name, x.delivery, x.visibility, x.result !== null]),
      );
      expect(g.events.map((x) => [x.id, x.name, x.priority, x.requires])).toEqual(cap.events.map((x) => [x.id, x.name, x.priority, x.requires]));
      expect(g.properties.map((x) => [x.id, x.name, x.requires])).toEqual(cap.properties.map((x) => [x.id, x.name, x.requires]));
      expect(g.traits.fields.map((f) => f.name)).toEqual(cap.traits.map((f) => f.name));
    }
    expect(MESSAGES.map((m) => [m.key, m.cls, m.kind])).toEqual(model.protocol.messages.map((m) => [m.key, m.clsCode, m.kind]));
    expect(PROTOCOL_TYPES.map((t) => t.name)).toEqual(model.protocol.types.map((t) => t.name));
    expect(CLASSES.map((c) => [c.code, c.name])).toEqual(model.protocol.classes.map((c) => [c.code, c.name]));
    for (const c of CLASSES) {
      expect(prefixType(c.code)).toBe(c.prefix);
    }
  });

  it('codec maxSize bounds every value the field types carry, so never undercuts the model', () => {
    for (const m of model.protocol.messages) {
      expect(MESSAGES.find((x) => x.key === m.key)!.codec.maxSize).toBeGreaterThanOrEqual(m.maxBody);
    }
    const led = CAPS.find((c) => c.name === 'fr.led')!;
    // blink: on_ms, off_ms and count are u16 (tag + 3 B each; range is not a codec bound), color u32 (tag + 5 B).
    expect(led.commands.find((c) => c.name === 'blink')!.args.maxSize).toBe(4 + 4 + 4 + 6);
  });

  it('names a system message that would shadow a hand-written export with a Msg suffix', () => {
    const messages = emitTs(model).find((f) => f.path === `${TS_GEN_DIR}/messages.ts`)!.content;
    expect(messages).toContain('export interface LogLineMsg {');
    expect(messages).toContain('export function decodeLogLine(bytes: Uint8Array): Decoded<LogLineMsg>');
  });

  it('fails on generated names that collide', () => {
    const clash = edited('schema/capabilities/button.cap.yaml', (y) => (y.events.traits = { id: 9, priority: 'normal' }));
    expect(() => emitTs(clash)).toThrow(/ButtonTraits .*collides with/);
    const setArgs = edited('schema/capabilities/led.cap.yaml', (y) => (y.events.set_args = { id: 9, priority: 'normal' }));
    expect(() => emitTs(setArgs)).toThrow(/LedSetArgs .*collides with/);
  });

  it('fails on an implicit enum field without a zero member', () => {
    const noZero = edited('schema/capabilities/led.cap.yaml', (y) => (y.types.Effect.enum = { none: 1, blink: 2 }));
    expect(() => emitTs(noZero)).toThrow(/enum Effect has no member with value 0/);
  });
});

describe('generateAll', () => {
  const tmp = mkdtempSync(join(tmpdir(), 'fr-gen-'));
  afterAll(() => rmSync(tmp, { recursive: true, force: true }));

  it('writes every output, then only what changed, and reports and removes orphans', () => {
    cpSync(join(ROOT, 'schema', 'protocol.yaml'), join(tmp, 'schema', 'protocol.yaml'));
    cpSync(join(ROOT, 'schema', 'registry.yaml'), join(tmp, 'schema', 'registry.yaml'));
    cpSync(join(ROOT, 'schema', 'capabilities'), join(tmp, 'schema', 'capabilities'), { recursive: true });
    const hand = join(tmp, 'packages', 'protocol', 'src', 'index.ts');
    mkdirSync(dirname(hand), { recursive: true });
    writeFileSync(hand, '// hand-written\n');

    const first = generateAll({ sourceDir: tmp });
    expect(first.written).toEqual(first.files);
    expect(first.files).toEqual(expect.arrayContaining([`${TS_GEN_DIR}/caps/led.ts`, `${VECTORS_DIR}/caps.json`, 'firmware/test/host/gen/vectors.inc']));
    expect(first.files.every((p) => GENERATED_ROOTS.some((r) => p.startsWith(`${r}/`)))).toBe(true);
    expect(generateAll({ sourceDir: tmp }).written).toEqual([]);
    expect(generateAll({ sourceDir: tmp, check: true }).stale).toEqual([]);

    const changed = `${TS_GEN_DIR}/caps/led.ts`;
    const missing = `${VECTORS_DIR}/serial.json`;
    const orphan = `${TS_GEN_DIR}/caps/knob.ts`;
    writeFileSync(join(tmp, changed), '// edited\n');
    rmSync(join(tmp, missing));
    writeFileSync(join(tmp, orphan), '// left over\n');
    writeFileSync(join(tmp, TS_GEN_DIR, '.DS_Store'), '');
    const check = generateAll({ sourceDir: tmp, check: true });
    expect(check.stale).toEqual([changed, orphan, missing].sort());
    expect(check.written).toEqual([]);
    expect(readFileSync(join(tmp, changed), 'utf8')).toBe('// edited\n');

    const fix = generateAll({ sourceDir: tmp });
    expect(fix.written.sort()).toEqual([changed, missing].sort());
    expect(fix.removed).toEqual([orphan]);
    expect(existsSync(join(tmp, orphan))).toBe(false);
    expect(existsSync(join(tmp, TS_GEN_DIR, '.DS_Store'))).toBe(true);
    expect(readFileSync(hand, 'utf8')).toBe('// hand-written\n');
    expect(generateAll({ sourceDir: tmp, check: true }).stale).toEqual([]);
  });

  it('the checkout has no stale TS outputs or vectors', () => {
    const r = generateAll({ sourceDir: ROOT, check: true });
    expect(r.stale.filter((p) => p.startsWith(`${TS_GEN_DIR}/`) || p.startsWith(`${VECTORS_DIR}/`))).toEqual([]);
  });

  it('throws SchemaError on an invalid schema', () => {
    const bad = mkdtempSync(join(tmpdir(), 'fr-gen-bad-'));
    try {
      cpSync(join(ROOT, 'schema'), join(bad, 'schema'), { recursive: true });
      writeFileSync(join(bad, 'schema', 'capabilities', 'led.cap.yaml'), 'capability: fr.led\nid: 2\n');
      expect(() => generateAll({ sourceDir: bad, check: true })).toThrow(/schema validation failed/);
    } finally {
      rmSync(bad, { recursive: true, force: true });
    }
  });
});
