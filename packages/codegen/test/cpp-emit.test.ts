describe('vectors.inc', () => {
  it('turns cases into values, decode-only checks and error checks', () => {
    const text = vectorsBody([
      { name: 'a', kind: 'cap', type: 'fr.led.set.args', value: { on: true, brightness: 0 }, hex: '0801 1000' },
      { name: 'b', kind: 'cap', type: 'fr.led.on.state', value: { on: true }, hex: '0801' },
      { name: 'c', kind: 'message', type: 'PRESENCE.PING', value: { t0: 2 }, hex: '0801 0802', decodeOnly: true } as VectorCase,
      { name: 'd', kind: 'cap', type: 'fr.button.click.event', value: null, hex: '0800', decodeOnly: true, error: 'out_of_range' } as VectorCase,
      { name: 'e', kind: 'cap', type: 'fr.led.toggle.args', value: {}, hex: '' },
      { name: 'f', kind: 'message', type: 'NET.DIRECTORY', value: { page: 0, pages: 1, entries: [{ addr: 18, mac: 'a0b1' }] }, hex: '1001 1a06 0812 1202a0b1' },
    ]);
    expect(text).toContain('inline constexpr size_t kCount = 6;');
    expect(text).toContain('x.on = true;\n        x.has_brightness = true;\n        x.brightness = 0;\n        v.value("a", "fr.led.set.args", x, enc, fr::cap::decode_led_set_args, "08011000", true);');
    expect(text).toContain('bool x = false;\n        x = true;\n        v.value("b", "fr.led.on.state", x, fr::cap::encode_led_on_state, fr::cap::decode_led_on_state, "0801", true);');
    expect(text).toContain('v.value("c", "PRESENCE.PING", x, enc, fr::proto::decode_presence_ping, "08010802", false);');
    expect(text).toContain('v.error("d", "fr.button.click.event", fr::cap::decode_button_click, "0800", fr::wire::DecodeErr::out_of_range);');
    expect(text).toContain('fr::proto::Empty x{};\n        v.value("e", "fr.led.toggle.args", x, enc, fr::proto::decode_empty, "", true);');
    expect(text).toContain('static constexpr uint8_t b0[] = {0xa0, 0xb1};');
    expect(text).toContain('x.entries.push_back(e0);');
  });

  it('keeps the input line of serial cases and checks their bytes', () => {
    const line = encodeSerialLine(0x16, Uint8Array.of(1, 2, 3, 4));
    const text = vectorsBody([{ name: 's', kind: 'serial', type: 'serial.LINK_PING', value: { type: 0x16, body: '01020304', line: `${line}\r\n` }, hex: Buffer.from(`${line}\r\n`).toString('hex'), decodeOnly: true } as VectorCase]);
    expect(text).toMatch(/v\.serial\("s", 0x16, body, "@fr1:[A-Za-z0-9_-]+", "@fr1:[A-Za-z0-9_-]+\\015\\n", false\);/);
  });

  it('rejects cases that do not fit the schema', () => {
    expect(() => vectorsBody([{ name: 'x', kind: 'cap', type: 'fr.led.set.args', value: { glow: 1 }, hex: '' }])).toThrow(/unknown field 'glow'/);
    expect(() => vectorsBody([{ name: 'x', kind: 'cap', type: 'fr.led.nope.args', value: {}, hex: '' }])).toThrow(/no generated codec/);
    const h = { flags: 0, cls: 3, kind: 1, seq: 1, net: 0, src: 0, dst: 0, epoch: 0, ttl: 0, port: 0 };
    const hex = Buffer.from(packHeader(h)).toString('hex');
    expect(() => vectorsBody([{ name: 'x', kind: 'header', type: 'header', value: { ...h, cls: 4 }, hex }])).toThrow(/header.cls is 4/);
  });

  it('renders every committed golden vector', () => {
    const cases = emitVectors(model()).cases;
    const text = vectorsBody(cases);
    const calls = text.match(/^ +v\.(value|error|header|envelope|serial)\(/gm)?.length ?? 0;
    expect(text).toContain(`inline constexpr size_t kCount = ${calls};`);
    expect(calls).toBeGreaterThanOrEqual(cases.length);
  });
});

