#!/bin/bash
# Creates local/ (git-ignored): your SSH public key for root on the board, a
# stable SSH host key for the board, a key that can only start the MCP server
# (qonu-mcp), and an ssh config that pins the host key.
set -euo pipefail
cd "$(dirname "$0")/.."
HOST=${QONU_HOSTNAME:-uriel}
mkdir -p local/ssh local/wifi

if [ ! -s local/authorized_keys ]; then
	for k in ~/.ssh/id_ed25519.pub ~/.ssh/id_ecdsa.pub ~/.ssh/id_rsa.pub; do
		[ -s "$k" ] && { cp "$k" local/authorized_keys; echo "setup: authorized_keys <- $k"; break; }
	done
	[ -s local/authorized_keys ] || { echo "setup: no SSH public key in ~/.ssh; run ssh-keygen -t ed25519" >&2; exit 1; }
fi

if [ ! -s local/ssh/ssh_host_ed25519_key ]; then
	ssh-keygen -q -t ed25519 -N "" -C "root@$HOST" -f local/ssh/ssh_host_ed25519_key
	echo "setup: generated board host key"
fi

if [ ! -s local/ssh/mcp_ed25519 ]; then
	ssh-keygen -q -t ed25519 -N "" -C "qonu-mcp" -f local/ssh/mcp_ed25519
	echo "setup: generated the MCP client key (the board pins it to qonu-mcp)"
fi

# The board's time zone: this computer's, unless local/timezone says otherwise (an IANA name, e.g. Europe/Berlin).
if [ ! -s local/timezone ]; then
	tz=$(readlink /etc/localtime 2>/dev/null | sed -n 's|.*/zoneinfo/||p')
	echo "${tz:-Etc/UTC}" > local/timezone
	echo "setup: board time zone ${tz:-Etc/UTC} (local/timezone)"
fi

echo "$HOST.local,10.55.0.1 $(cut -d' ' -f1,2 local/ssh/ssh_host_ed25519_key.pub)" > local/known_hosts
cat > local/ssh_config <<CFG
# Generated by scripts/setup-local.sh. Use: ssh -F local/ssh_config $HOST
Host $HOST
	HostName $HOST.local
Host $HOST-usb
	HostName 10.55.0.1
# MCP clients: this key can only start qonu-mcp (forced command on the board).
Host $HOST-mcp
	HostName $HOST.local
	IdentityFile $PWD/local/ssh/mcp_ed25519
	IdentitiesOnly yes
	BatchMode yes
Host $HOST $HOST-usb $HOST-mcp
	User root
	HostKeyAlias $HOST.local
	UserKnownHostsFile $PWD/local/known_hosts
	StrictHostKeyChecking yes
	ConnectTimeout 5
	ServerAliveInterval 15
CFG
